// 工作台交互逻辑分片 N（零外网依赖单文件工作台分片模块，严格 <= 300 行）
export function buildWbLogicN() {
  return [
  "    function handleSubagentMessage(rawText) {",
  "      const text = String(rawText || '').trim();",
  "      if (!text) return;",
  "",
  "      const sel = getSelectionInfo();",
  "      const canvasSummary = getCanvasSelectionSummary(sel);",
  "      const txtItem = state.selectedTextItem;",
  "      const ctrl = state.lastClickedControl;",
  "      const effMode = resolveEffectiveFocusMode(canvasSummary);",
  "",
  "      const tag = effMode === 'text' && txtItem",
  "        ? `文本：${txtItem.text}`",
  "        : effMode === 'control' && ctrl",
  "          ? `按钮：${ctrl.label}（${ctrl.area}）`",
  "          : (canvasSummary || '当前画布');",
  "",
  "      state.chatMessages.push({ role: 'user', text, tag });",
  "      const undoStepMatch = text.match(/(?:撤销|回退|历史).*?(\\d{2,3})\\s*步/);",
  "      if (undoStepMatch && typeof setMaxUndoSteps === 'function') {",
  "        const applied = setMaxUndoSteps(Number(undoStepMatch[1]));",
  "        state.chatMessages.push({ role: 'agent', html: `已将画布最大撤销历史步数调整为 <b>${applied} 步</b>（快捷键 <code>Ctrl+Z</code> 撤销，<code>Ctrl+Y</code> 重做）。` });",
  "        renderRightSidebar();",
  "        return;",
  "      }",
  "",
  "      if (state.pendingGithubInstall && /^(行|好|可以|没问题|ok|yes|装吧|只接第一个)/i.test(text)) {",
  "        confirmGithubInstall(text.includes('一') ? 'first' : 'all');",
  "        return;",
  "      }",
  "",
  "      const q = text.toLowerCase();",
  "",
  "      // 0) 当所选元素为「文本：某某某」时：支持双击/口述改名、改文字颜色与字重、或解释该文本在当前卡片中的业务含义！",
  "      if (effMode === 'text' && txtItem) {",
  "        const renameM = text.match(/(?:改名(?:为|成|叫)?|改(?:为|成)|文字改(?:为|成)|叫)\\s*[「\"“']?([^」\"”'，。]{1,22})[」\"”']?/);",
  "        const colorDict = [",
  "          { re: /红|red/, hex: '#dc2626', name: '红色 (#dc2626)' },",
  "          { re: /蓝|blue/, hex: '#2563eb', name: '蓝色 (#2563eb)' },",
  "          { re: /绿|green|翠/, hex: '#16a34a', name: '绿色 (#16a34a)' },",
  "          { re: /橙|橘|黄|amber|orange/, hex: '#d97706', name: '琥珀橙 (#d97706)' },",
  "          { re: /紫|purple/, hex: '#7c3aed', name: '紫色 (#7c3aed)' },",
  "          { re: /灰|gray/, hex: '#64748b', name: '灰色 (#64748b)' }",
  "        ];",
  "        const hitColor = colorDict.find((c) => c.re.test(q));",
  "",
  "        if (/恢复|还原|默认|重置/.test(q)) {",
  "          delete state.textStyleOverrides[txtItem.key];",
  "          renderAll();",
  "          state.chatMessages.push({ role: 'agent', html: `已将「<b>文本：${esc(txtItem.text)}</b>」恢复为默认文字样式。` });",
  "          renderRightSidebar();",
  "          return;",
  "        }",
  "",
  "        if (hitColor || /加粗|粗体|大一点|小一点/.test(q)) {",
  "          const prev = state.textStyleOverrides[txtItem.key] || {};",
  "          const notes = [];",
  "          if (hitColor) { prev.color = hitColor.hex; notes.push(`颜色改为<b>${hitColor.name}</b>`); }",
  "          if (/加粗|粗体/.test(q)) { prev.fontWeight = '700'; notes.push('字体加粗'); }",
  "          if (/大一点|放大/.test(q)) { prev.fontSize = '13px'; notes.push('字号调大'); }",
  "          if (/小一点|缩小/.test(q)) { prev.fontSize = '10.5px'; notes.push('字号调小'); }",
  "          state.textStyleOverrides[txtItem.key] = prev;",
  "          renderAll();",
  "          state.chatMessages.push({ role: 'agent', html: `已对「<b>文本：${esc(txtItem.text)}</b>」应用样式修改：${notes.join('、')}。` });",
  "          renderRightSidebar();",
  "          return;",
  "        }",
  "",
  "        if (renameM && renameM[1] && !/什么意思|干什么|作用/.test(q)) {",
  "          const oldName = txtItem.text;",
  "          applyTextRenameByKey(txtItem.key, renameM[1]);",
  "          renderAll();",
  "          state.chatMessages.push({ role: 'agent', html: `已将原文本「${esc(oldName)}」重命名为「<b>${esc(txtItem.text)}</b>」（你也可以直接在界面上双击任意文字改名）。` });",
  "          renderRightSidebar();",
  "          return;",
  "        }",
  "",
  "        const ownerNote = txtItem.ownerTitle ? `所属卡片「<b>${esc(txtItem.ownerTitle)}</b>」内的` : '界面上的';",
  "        state.chatMessages.push({",
  "          role: 'agent',",
  "          html: `当前选中的是${ownerNote}<b>${esc(txtItem.roleLabel)}</b>：「<b>${esc(txtItem.text)}</b>」。<br>你可以直接在原位置<b>双击它修改名字</b>，或者对我说「<b>改名叫某某某</b>」、「<b>改成蓝色加粗</b>」。`",
  "        });",
  "        renderRightSidebar();",
  "        return;",
  "      }",
  "",
  "      if (effMode === 'control' && ctrl) {",
  "        const colorDict = [",
  "          { re: /红|red|警示/, hex: '#dc2626', name: '红色 (#dc2626)' },",
  "          { re: /蓝|blue/, hex: '#2563eb', name: '蓝色 (#2563eb)' },",
  "          { re: /绿|green|翠/, hex: '#16a34a', name: '绿色 (#16a34a)' },",
  "          { re: /橙|橘|黄|amber|orange/, hex: '#d97706', name: '琥珀橙 (#d97706)' },",
  "          { re: /紫|purple|violet/, hex: '#7c3aed', name: '紫色 (#7c3aed)' },",
  "          { re: /粉|玫|pink|rose/, hex: '#e11d48', name: '玫红色 (#e11d48)' },",
  "          { re: /灰|gray|grey/, hex: '#64748b', name: '灰色 (#64748b)' },",
  "          { re: /黑|深色|black/, hex: '#0f172a', name: '深黑色 (#0f172a)' },",
  "          { re: /白|white/, hex: '#ffffff', name: '白色 (#ffffff)' }",
  "        ];",
  "",
  "        if (/恢复|还原|默认|重置/.test(q)) {",
  "          delete state.controlStyleOverrides[ctrl.key];",
  "          renderAll();",
  "          state.chatMessages.push({",
  "            role: 'agent',",
  "            html: `已将按钮「<b>${esc(ctrl.label)}</b>」（${esc(ctrl.area)}）恢复为默认样式与文案。`",
  "          });",
  "          renderRightSidebar();",
  "          return;",
  "        }",
  "",
  "        const prev = state.controlStyleOverrides[ctrl.key] || { origLabel: ctrl.label };",
  "        const changes = [];",
  "        const matchedColor = colorDict.find((c) => c.re.test(q));",
  "        if (matchedColor) {",
  "          if (/背景|底色|填充/.test(q)) {",
  "            prev.background = matchedColor.hex;",
  "            if (matchedColor.hex !== '#ffffff') prev.color = '#ffffff';",
  "            changes.push(`底色改为<b>${matchedColor.name}</b>`);",
  "          } else {",
  "            prev.color = matchedColor.hex;",
  "            if (!prev.fontWeight) prev.fontWeight = '600';",
  "            changes.push(`文字颜色改为<b>${matchedColor.name}</b>`);",
  "          }",
  "        }",
  "        if (/边框/.test(q) && matchedColor) {",
  "          prev.borderColor = matchedColor.hex;",
  "          changes.push('加上同色边框');",
  "        }",
  "        if (/加粗|粗体/.test(q)) {",
  "          prev.fontWeight = '700';",
  "          changes.push('字体加粗');",
  "        }",
  "        if (/大一点|放大|大号/.test(q)) {",
  "          prev.fontSize = '12.5px';",
  "          changes.push('字号调大');",
  "        } else if (/小一点|缩小|小号/.test(q)) {",
  "          prev.fontSize = '10px';",
  "          changes.push('字号调小');",
  "        }",
  "        const renameMatch = text.match(/(?:改名(?:为|成|叫)?|文字改(?:为|成)|叫)\\s*[「\"“']?([^」\"”'，。,\\s]{1,10})[」\"”']?/);",
  "        if (renameMatch && renameMatch[1]) {",
  "          prev.customLabel = renameMatch[1];",
  "          ctrl.label = renameMatch[1];",
  "          changes.push(`按钮文案改为「<b>${esc(renameMatch[1])}</b>」`);",
  "        }",
  "",
  "        if (changes.length > 0) {",
  "          state.controlStyleOverrides[ctrl.key] = prev;",
  "          renderAll();",
  "          applyAllControlStyleOverrides();",
  "          state.chatMessages.push({",
  "            role: 'agent',",
  "            html: `已针对上次点击的按钮「<b>${esc(ctrl.label)}</b>」（${esc(ctrl.area)}）实时修改：${changes.join('、')}。<br><span style=\"color:var(--text-muted);\">随时可说「恢复默认」还原原样。</span>`",
  "          });",
  "          renderRightSidebar();",
  "          return;",
  "        }",
  "",
  "        state.chatMessages.push({",
  "          role: 'agent',",
  "          html: `当前指向的是${esc(ctrl.area)}按钮「<b>${esc(ctrl.label)}</b>」。你可以直接告诉我怎么改它，例如：「<b>把这个${esc(ctrl.label)}改成红色的字</b>」、「<b>底色改成蓝色</b>」、「<b>加粗</b>」或「<b>改名叫直通</b>」。`",
  "        });",
  "        renderRightSidebar();",
  "        return;",
  "      }",
  "",
  "      if (sel.kind === 'group') {",
  "        const grp = sel.group;",
  "        const renameGrp = text.match(/(?:改名(?:为|成|叫)?|标题改(?:为|成)|叫)\\s*[「\"“']?([^」\"”'，。]{1,18})[」\"”']?/);",
  "        if (renameGrp && renameGrp[1]) {",
  "          grp.title = renameGrp[1].trim();",
  "          renderAll();",
  "          state.chatMessages.push({ role: 'agent', html: `已将组合框标题更新为「<b>${esc(grp.title)}</b>」。` });",
  "          renderRightSidebar();",
  "          return;",
  "        }",
  "        if (/合并|折叠成子/.test(q)) {",
  "          convertGroupToSubgraph(grp.id);",
  "          state.chatMessages.push({ role: 'agent', html: `已将组合框「<b>${esc(grp.title)}</b>」转换为合并子节点。` });",
  "          renderRightSidebar();",
  "          return;",
  "        }",
  "        const memberNames = grp.memberIds.map((id) => getActiveNodesList().find((n) => n.id === id)?.title).filter(Boolean);",
  "        state.chatMessages.push({",
  "          role: 'agent',",
  "          html: `当前选中的是组合框「<b>${esc(grp.title)}</b>」，框住了 ${memberNames.length} 张卡片（${memberNames.map((n) => esc(n)).join('、')}）。拖动或缩放内部任意卡片时该背景框会自动保持固定边距伸缩，点框顶栏右侧「<b>转为合并</b>」可一键折叠为子节点。`",
  "        });",
  "        renderRightSidebar();",
  "        return;",
  "      }",
  "",
  "      if (sel.kind === 'link') {",
  "        const { link, src, dst, muted } = sel;",
  "        const outPort = src ? (src.outputs || []).find((o) => o.id === link.fromSlot) : null;",
  "        const inPort = dst ? (dst.inputs || []).find((i) => i.id === link.toSlot) : null;",
  "        if (src && dst && src.id === dst.id) {",
  "          state.chatMessages.push({",
  "            role: 'agent',",
  "            html: `这段连线是「<b>${esc(src.title)}</b>」的<b>自循环回流线</b>：<br>1. <b>前一步传出</b>：从「${esc(outPort ? outPort.name : '回流口')}」把尚未完全达标的文本或产物退回；<br>2. <b>下一步拿来干什么</b>：送回自身的「${esc(inPort ? inPort.name : '入口')}」重新做下一轮打磨，最多重复 <b>${link.maxLoops || 3} 次</b>，达标后改走放行口进入下游组件。`",
  "          });",
  "        } else {",
  "          const usageHint = link.type === 'ARTIFACT'",
  "            ? '拿到这份真实构建产物或代码快照后，直接在上面执行体积比对、安装运行或静态扫描，不用重新编译'",
  "            : link.type === 'SIGNAL'",
  "              ? '根据传过来的 0/1/2/3 判定结果决定是唤醒下游重型测试，还是直接拦截打回'",
  "              : link.type === 'TEXT'",
  "                ? '读取前一步生成的原始诊断报告或日志正文，提炼问题行号或做语义评审'",
  "                : link.type === 'SPEC'",
  "                  ? '基于上游整理好的规格草案，进一步核查遗漏或生成施工指令'",
  "                  : '接收前一步产出的上下文并驱动当前组件执行任务';",
  "          state.chatMessages.push({",
  "            role: 'agent',",
  "            html: `这段连线代表前后两个组件之间的数据交接：<br>1. <b>前一个组件传什么</b>：「<b>${esc(src ? src.title : '')}</b>」通过出口「${esc(outPort ? outPort.name : link.fromSlot)}」产出 <b>${esc(PORT_LABELS[link.type] || link.type)}</b>；<br>2. <b>下一个组件拿来干什么</b>：传给「<b>${esc(dst ? dst.title : '')}</b>」的入口「${esc(inPort ? inPort.name : link.toSlot)}」，后者${usageHint}。${muted ? '<br>3. <b>当前状态</b>：因前一个组件关闭了对应转接功能（或开启了跳过），此连线当前呈<b>灰色暂停态</b>。' : ''}`",
  "          });",
  "        }",
  "        renderRightSidebar();",
  "        return;",
  "      }",
  "",
  "      if (sel.kind === 'sb-link') {",
  "        const srcMods = sel.src && sel.src.modules && sel.src.modules.length ? `（由 ${sel.src.modules.map((m) => m.name).slice(0, 2).join('、')} 等产出状态与数据）` : '';",
  "        const dstMods = sel.dst && sel.dst.modules && sel.dst.modules.length ? `（驱动 ${sel.dst.modules.map((m) => m.name).slice(0, 2).join('、')} 继续处理）` : '';",
  "        state.chatMessages.push({",
  "          role: 'agent',",
  "          html: `这段业务流连线代表：<br>1. <b>前置环节交付</b>：「<b>${esc(sel.src ? sel.src.title : '')}</b>」完成后${esc(srcMods)}，把已校验的业务上下文往后传递；<br>2. <b>后续环节承接</b>：「<b>${esc(sel.dst ? sel.dst.title : '')}</b>」接手该数据继续推进客户流程${esc(dstMods)}。`",
  "        });",
  "        renderRightSidebar();",
  "        return;",
  "      }",
  "",
  "      if (sel.kind === 'multi') {",
  "        const names = sel.nodes.map((n) => `「${esc(n.title)}」`).join('、');",
  "        state.chatMessages.push({",
  "          role: 'agent',",
  "          html: `你选中的 ${names} 构成了递进协作组合。如果想让画布更简洁，直接点选中卡片正上方悬浮条里的「<b>合并 (${sel.nodes.length})</b>」即可将它们折叠成一个子节点（双击可随时下钻进入子流）。`",
  "        });",
  "        renderRightSidebar();",
  "        return;",
  "      }",
  "",
  "      if (sel.kind === 'single' && sel.node.isSubgraph && sel.node.subgraph) {",
  "        const realInner = sel.node.subgraph.nodes.filter((n) => !n.isBoundary);",
  "        state.chatMessages.push({",
  "          role: 'agent',",
  "          html: `子节点「<b>${esc(sel.node.title)}</b>」在界面上封装了 ${realInner.length} 张内部卡片（${realInner.map((n) => esc(n.title)).join(' → ')}），并未改动后台代码文件。双击该卡片或点上方「进入子流」即可查看或调整内部连线。`",
  "        });"
  ].join('\n');
}
