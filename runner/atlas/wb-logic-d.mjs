// 工作台交互逻辑分片 D（零外网依赖单文件工作台分片模块，严格 <= 300 行）
export function buildWbLogicD() {
  return [
  "      state.selectedGroupId = null;",
  "      state.editingGroupId = null;",
  "      state.colorPickerOpen = false;",
  "      state.selectedNodeIds = new Set(members);",
  "      renderAll();",
  "      showToast('已解除组合框（内部节点与连线完整保留）');",
  "    }",
  "",
  "    function convertGroupToSubgraph(groupId) {",
  "      if (isSandboxReadOnly()) return;",
  "      const groups = getActiveGroupsList();",
  "      const grp = groups.find((g) => g.id === groupId);",
  "      if (!grp) return;",
  "      const memberIds = [...grp.memberIds];",
  "      if (memberIds.length < 2) {",
  "        showToast('组合内至少需要 2 张卡片才能转为合并子节点');",
  "        return;",
  "      }",
  "      const savedTitle = grp.title.replace(/^组合[:：]\\s*/, '');",
  "      const savedColor = grp.colorKey;",
  "      const gObj = getActiveGraphObject();",
  "      gObj.groups = gObj.groups.filter((g) => g.id !== groupId);",
  "      state.selectedGroupId = null;",
  "      state.editingGroupId = null;",
  "      state.selectedNodeIds = new Set(memberIds);",
  "      mergeSelectedIntoSubgraph({ customTitle: savedTitle, customColorKey: savedColor });",
  "      showToast(`已将组合「${grp.title}」转换为合并子节点`);",
  "    }",
  "",
  "    // ============================================================================",
  "    // 5. ComfyUI Subgraph 纯界面「合并为子节点 / 进入子流 / 返回父级 / 拆散还原 / 与组合互转」引擎",
  "    // ============================================================================",
  "    function mergeSelectedIntoSubgraph(opts = {}) {",
  "      if (isSandboxReadOnly()) return;",
  "",
  "      if (state.page === 'workshop') {",
  "        const graph = getActiveWorkshopGraph();",
  "        const picked = graph.nodes.filter((n) => state.selectedNodeIds.has(n.id) && !n.isBoundary);",
  "        if (picked.length < 2) {",
  "          showToast('请按住 Ctrl 多选至少 2 张卡片后再点合并');",
  "          return;",
  "        }",
  "        const pickedSet = new Set(picked.map((n) => n.id));",
  "        const minX = Math.min(...picked.map((n) => n.x));",
  "        const minY = Math.min(...picked.map((n) => n.y));",
  "        const maxX = Math.max(...picked.map((n) => n.x + (n.w || 252)));",
  "",
  "        const internalLinks = [];",
  "        const incomingLinks = [];",
  "        const outgoingLinks = [];",
  "        const remainLinks = [];",
  "",
  "        graph.links.forEach((lk) => {",
  "          const fIn = pickedSet.has(lk.fromNode);",
  "          const tIn = pickedSet.has(lk.toNode);",
  "          if (fIn && tIn) internalLinks.push(lk);",
  "          else if (!fIn && tIn) incomingLinks.push(lk);",
  "          else if (fIn && !tIn) outgoingLinks.push(lk);",
  "          else remainLinks.push(lk);",
  "        });",
  "",
  "        // Shift inner nodes cleanly so boundary input sits on left and boundary output sits on right",
  "        const shiftX = 310 - minX;",
  "        const shiftY = 95 - minY;",
  "        const innerNodes = picked.map((n) => ({",
  "          ...n,",
  "          x: Math.round(n.x + shiftX),",
  "          y: Math.round(n.y + shiftY)",
  "        }));",
  "",
  "        const sgId = 'sg-ws-' + Date.now();",
  "        const sgInputs = [];",
  "        const sgOutputs = [];",
  "        const boundaryInOutputs = [];",
  "        const boundaryOutInputs = [];",
  "",
  "        incomingLinks.forEach((lk, idx) => {",
  "          const dstNode = innerNodes.find((n) => n.id === lk.toNode);",
  "          const origPort = dstNode ? (dstNode.inputs || []).find((p) => p.id === lk.toSlot) : null;",
  "          const slotId = `sgin_${idx}`;",
  "          const pType = origPort ? origPort.type : lk.type;",
  "          const pName = origPort ? origPort.name : `入口 ${idx + 1}`;",
  "          sgInputs.push({ id: slotId, name: pName, type: pType, _innerNode: lk.toNode, _innerSlot: lk.toSlot });",
  "          boundaryInOutputs.push({ id: slotId, name: pName, type: pType });",
  "          internalLinks.push({",
  "            id: `b_in_${idx}_${Date.now()}`,",
  "            fromNode: '__sg_in__',",
  "            fromSlot: slotId,",
  "            toNode: lk.toNode,",
  "            toSlot: lk.toSlot,",
  "            type: lk.type",
  "          });",
  "          remainLinks.push({",
  "            id: lk.id,",
  "            fromNode: lk.fromNode,",
  "            fromSlot: lk.fromSlot,",
  "            toNode: sgId,",
  "            toSlot: slotId,",
  "            type: lk.type",
  "          });",
  "        });",
  "",
  "        outgoingLinks.forEach((lk, idx) => {",
  "          const srcNode = innerNodes.find((n) => n.id === lk.fromNode);",
  "          const origPort = srcNode ? (srcNode.outputs || []).find((p) => p.id === lk.fromSlot) : null;",
  "          const slotId = `sgout_${idx}`;",
  "          const pType = origPort ? origPort.type : lk.type;",
  "          const pName = origPort ? origPort.name : `出口 ${idx + 1}`;",
  "          sgOutputs.push({ id: slotId, name: pName, type: pType, _innerNode: lk.fromNode, _innerSlot: lk.fromSlot });",
  "          boundaryOutInputs.push({ id: slotId, name: pName, type: pType });",
  "          internalLinks.push({",
  "            id: `b_out_${idx}_${Date.now()}`,",
  "            fromNode: lk.fromNode,",
  "            fromSlot: lk.fromSlot,",
  "            toNode: '__sg_out__',",
  "            toSlot: slotId,",
  "            type: lk.type",
  "          });",
  "          remainLinks.push({",
  "            id: lk.id,",
  "            fromNode: sgId,",
  "            fromSlot: slotId,",
  "            toNode: lk.toNode,",
  "            toSlot: lk.toSlot,",
  "            type: lk.type",
  "          });",
  "        });",
  "",
  "        if (sgInputs.length === 0) {",
  "          sgInputs.push({ id: 'sgin_default', name: '子流入口', type: 'ANY' });",
  "          boundaryInOutputs.push({ id: 'sgin_default', name: '子流入口', type: 'ANY' });",
  "        }",
  "        if (sgOutputs.length === 0) {",
  "          sgOutputs.push({ id: 'sgout_default', name: '子流出口', type: 'ANY' });",
  "          boundaryOutInputs.push({ id: 'sgout_default', name: '子流出口', type: 'ANY' });",
  "        }",
  "",
  "        const innerRightEdge = Math.round(maxX + shiftX + 75);",
  "        const boundaryInNode = instantiateWorkshopNode('tpl-blank', '__sg_in__', 32, 130, {",
  "          title: '父级传入接口',",
  "          tip: '代表从外部父工作流传入本子节点的接口（纯视图边界）',",
  "          isBlank: false,",
  "          isBoundary: 'in',",
  "          w: 210,",
  "          inputs: [],",
  "          outputs: boundaryInOutputs,",
  "          slots: []",
  "        });",
  "        const boundaryOutNode = instantiateWorkshopNode('tpl-blank', '__sg_out__', innerRightEdge, 130, {",
  "          title: '向父级传出接口',",
  "          tip: '代表从本子节点传回外部父工作流的接口（纯视图边界）',",
  "          isBlank: false,",
  "          isBoundary: 'out',",
  "          w: 210,",
  "          inputs: boundaryOutInputs,",
  "          outputs: [],",
  "          slots: []",
  "        });",
  "",
  "        const sgTitle = opts.customTitle || `${picked[0].title.slice(0, 6)}等 (${picked.length} 项合并)`;",
  "        const inheritedColor = opts.customColorKey || picked.find((n) => n.colorKey && n.colorKey !== 'none')?.colorKey || null;",
  "        const sgNode = instantiateWorkshopNode('tpl-blank', sgId, minX, minY, {",
  "          title: sgTitle,",
  "          tip: `纯界面合并的子节点（内含 ${picked.map((n) => n.title).join('、')}）· 双击进入子流，也可随时转换为组合框`,",
  "          isBlank: false,",
  "          isSubgraph: true,",
  "          colorKey: inheritedColor,",
  "          w: 268,",
  "          inputs: sgInputs,",
  "          outputs: sgOutputs,",
  "          slots: [],",
  "          subgraph: {",
  "            nodes: [boundaryInNode, ...innerNodes, boundaryOutNode],",
  "            links: internalLinks,",
  "            groups: []",
  "          }",
  "        });",
  "",
  "        getActiveGroupsList().forEach((g) => {",
  "          const hadAny = g.memberIds.some((id) => pickedSet.has(id));",
  "          g.memberIds = g.memberIds.filter((id) => !pickedSet.has(id));",
  "          if (hadAny && g.memberIds.length > 0) g.memberIds.push(sgId);",
  "        });",
  "",
  "        graph.nodes = graph.nodes.filter((n) => !pickedSet.has(n.id));",
  "        graph.nodes.push(sgNode);",
  "        graph.links = remainLinks;",
  "        pruneActiveGroups();",
  "        state.selectedGroupId = null;",
  "        state.colorPickerOpen = false;",
  "        state.selectedNodeIds = new Set([sgId]);",
  "        state.selectedLinkId = null;",
  "        renderAll();",
  "        if (!opts.customTitle) showToast(`已将 ${picked.length} 张卡片合并为子节点（双击可进入内部子流）`);",
  "      } else {",
  "        // 项目看板 UI Subgraph Merge (Zero backend code change — pure visual grouping!)",
  "        const container = getActiveSandboxContainer();",
  "        const picked = container.nodes.filter((n) => state.selectedNodeIds.has(n.id));",
  "        if (picked.length < 2) {",
  "          showToast('请多选至少 2 张看板卡片后再点合并');",
  "          return;",
  "        }",
  "        const pickedSet = new Set(picked.map((n) => n.id));",
  "        const minX = Math.min(...picked.map((n) => n.x));",
  "        const minY = Math.min(...picked.map((n) => n.y));",
  "",
  "        const sgId = 'sg-sb-' + Date.now();",
  "        const externalTargets = new Set();",
  "        const exitSourcesMap = []; // record which inner node originally linked to external target for lossless unpack!",
  "",
  "        picked.forEach((n) => {",
  "          const keptInternal = [];",
  "          (n.nextIds || []).forEach((tid) => {",
  "            if (pickedSet.has(tid)) {",
  "              keptInternal.push(tid);",
  "            } else {",
  "              externalTargets.add(tid);",
  "              exitSourcesMap.push({ fromInner: n.id, toExternal: tid });",
  "            }",
  "          });",
  "          n.nextIds = keptInternal;",
  "        });",
  "",
  "        const entrySourcesMap = [];",
  "        container.nodes.forEach((n) => {",
  "          if (pickedSet.has(n.id)) return;",
  "          const updated = [];",
  "          (n.nextIds || []).forEach((tid) => {",
  "            if (pickedSet.has(tid)) {",
  "              entrySourcesMap.push({ fromExternal: n.id, toInner: tid });",
  "              if (!updated.includes(sgId)) updated.push(sgId);",
  "            } else {",
  "              updated.push(tid);",
  "            }",
  "          });",
  "          n.nextIds = updated;",
  "        });",
  "",
  "        const shiftX = 80 - minX;",
  "        const shiftY = 110 - minY;",
  "        const innerNodes = picked.map((n) => ({",
  "          ...n,",
  "          x: Math.round(n.x + shiftX),",
  "          y: Math.round(n.y + shiftY)",
  "        }));"
  ].join('\n');
}
