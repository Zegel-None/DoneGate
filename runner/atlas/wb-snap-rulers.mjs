// Visual Studio 风格卡片缩放与移动等宽/等高标尺磁吸及边缘对齐参考线模块
export function buildWbSnapRulers() {
  return [
  "    // 13. 桌面级级联右键菜单",
  "    // ============================================================================",
  "    ",
  "    // ============================================================================",
  "    // 13b. Visual Studio 风格缩放/移动智能标尺（等宽/等高标尺磁吸 + 边缘对齐参考线）",
  "    // ============================================================================",
  "    function clearSnaplines() {",
  "      const svg = document.getElementById('snaplines-svg');",
  "      if (svg) svg.innerHTML = '';",
  "    }",
  "",
  "    function computeResizeWithVsSnap(resizingId, rawW, rawH, minW = 164, minH = 72) {",
  "      const nodes = getActiveNodesList();",
  "      const selfNode = nodes.find((n) => n.id === resizingId);",
  "      if (!selfNode) return { w: Math.max(minW, rawW), h: Math.max(minH, rawH) };",
  "",
  "      const siblings = [];",
  "      nodes.forEach((n) => {",
  "        if (n.id === resizingId) return;",
  "        const el = document.getElementById(`card-${n.id}`);",
  "        if (!el) return;",
  "        siblings.push({",
  "          id: n.id,",
  "          title: n.title,",
  "          x: el.offsetLeft,",
  "          y: el.offsetTop,",
  "          w: el.offsetWidth,",
  "          h: el.offsetHeight,",
  "          right: el.offsetLeft + el.offsetWidth,",
  "          bottom: el.offsetTop + el.offsetHeight",
  "        });",
  "      });",
  "",
  "      const SNAP_TOL = 8;",
  "      let finalW = rawW;",
  "      let finalH = rawH;",
  "      let matchedWidthCards = [];",
  "      let matchedHeightCards = [];",
  "      let alignRightCard = null;",
  "      let alignBottomCard = null;",
  "",
  "      // 1) Check Equal-Width matches (Visual Studio size snap, respecting minW!)",
  "      let bestWDiff = SNAP_TOL + 1;",
  "      siblings.forEach((sib) => {",
  "        if (sib.w < minW) return;",
  "        const diff = Math.abs(rawW - sib.w);",
  "        if (diff <= SNAP_TOL && diff < bestWDiff) {",
  "          bestWDiff = diff;",
  "          finalW = sib.w;",
  "        }",
  "      });",
  "      if (bestWDiff <= SNAP_TOL) {",
  "        matchedWidthCards = siblings.filter((sib) => Math.abs(sib.w - finalW) <= 1);",
  "      } else {",
  "        siblings.forEach((sib) => {",
  "          const candW = sib.right - selfNode.x;",
  "          if (candW < minW) return;",
  "          const edgeDiff = Math.abs((selfNode.x + rawW) - sib.right);",
  "          if (edgeDiff <= SNAP_TOL) {",
  "            finalW = candW;",
  "            alignRightCard = sib;",
  "          }",
  "        });",
  "      }",
  "",
  "      // 2) Check Equal-Height matches (Visual Studio size snap, respecting minH!)",
  "      let bestHDiff = SNAP_TOL + 1;",
  "      siblings.forEach((sib) => {",
  "        if (sib.h < minH) return;",
  "        const diff = Math.abs(rawH - sib.h);",
  "        if (diff <= SNAP_TOL && diff < bestHDiff) {",
  "          bestHDiff = diff;",
  "          finalH = sib.h;",
  "        }",
  "      });",
  "      if (bestHDiff <= SNAP_TOL) {",
  "        matchedHeightCards = siblings.filter((sib) => Math.abs(sib.h - finalH) <= 1);",
  "      } else {",
  "        siblings.forEach((sib) => {",
  "          const candH = sib.bottom - selfNode.y;",
  "          if (candH < minH) return;",
  "          const edgeDiff = Math.abs((selfNode.y + rawH) - sib.bottom);",
  "          if (edgeDiff <= SNAP_TOL) {",
  "            finalH = candH;",
  "            alignBottomCard = sib;",
  "          }",
  "        });",
  "      }",
  "      finalW = Math.max(minW, finalW);",
  "      finalH = Math.max(minH, finalH);",
  "",
  "      // Render Visual Studio Snaplines & Dimension Rulers onto #snaplines-svg",
  "      const svg = document.getElementById('snaplines-svg');",
  "      const parts = [];",
  "      const sx = selfNode.x;",
  "      const sy = selfNode.y;",
  "",
  "      if (alignRightCard) {",
  "        const rx = sx + finalW;",
  "        const y1 = Math.min(sy, alignRightCard.y) - 14;",
  "        const y2 = Math.max(sy + finalH, alignRightCard.bottom) + 14;",
  "        parts.push(`<line class=\"vs-align-line\" x1=\"${rx}\" y1=\"${y1}\" x2=\"${rx}\" y2=\"${y2}\"></line>`);",
  "      }",
  "      if (alignBottomCard) {",
  "        const by = sy + finalH;",
  "        const x1 = Math.min(sx, alignBottomCard.x) - 14;",
  "        const x2 = Math.max(sx + finalW, alignBottomCard.right) + 14;",
  "        parts.push(`<line class=\"vs-align-line\" x1=\"${x1}\" y1=\"${by}\" x2=\"${x2}\" y2=\"${by}\"></line>`);",
  "      }",
  "",
  "      // Equal-Width Horizontal Ruler (`|--- W: 252px (与 N 张卡片等宽) ---|`)",
  "      if (matchedWidthCards.length > 0) {",
  "        const ry = sy - 16;",
  "        parts.push(`",
  "          <line class=\"vs-size-ruler\" x1=\"${sx}\" y1=\"${ry}\" x2=\"${sx + finalW}\" y2=\"${ry}\"></line>",
  "          <line class=\"vs-size-ruler\" x1=\"${sx}\" y1=\"${ry - 5}\" x2=\"${sx}\" y2=\"${ry + 5}\"></line>",
  "          <line class=\"vs-size-ruler\" x1=\"${sx + finalW}\" y1=\"${ry - 5}\" x2=\"${sx + finalW}\" y2=\"${ry + 5}\"></line>",
  "        `);",
  "        const labelTxt = `W: ${finalW}px · 与 ${matchedWidthCards.length} 张卡片等宽`;",
  "        const pillW = labelTxt.length * 6.8 + 16;",
  "        const midX = sx + finalW / 2;",
  "        parts.push(`",
  "          <rect x=\"${midX - pillW / 2}\" y=\"${ry - 10}\" width=\"${pillW}\" height=\"19\" rx=\"5\" fill=\"#e11d48\"></rect>",
  "          <text class=\"vs-ruler-label\" x=\"${midX}\" y=\"${ry + 3}\" text-anchor=\"middle\">${esc(labelTxt)}</text>",
  "        `);",
  "        // Highlight reference width rulers on the matched sibling cards!",
  "        matchedWidthCards.forEach((mc) => {",
  "          const mry = mc.y - 10;",
  "          parts.push(`",
  "            <line class=\"vs-size-match-ref\" x1=\"${mc.x}\" y1=\"${mry}\" x2=\"${mc.x + mc.w}\" y2=\"${mry}\"></line>",
  "            <line class=\"vs-size-match-ref\" x1=\"${mc.x}\" y1=\"${mry - 4}\" x2=\"${mc.x}\" y2=\"${mry + 4}\"></line>",
  "            <line class=\"vs-size-match-ref\" x1=\"${mc.x + mc.w}\" y1=\"${mry - 4}\" x2=\"${mc.x + mc.w}\" y2=\"${mry + 4}\"></line>",
  "          `);",
  "        });",
  "      }",
  "",
  "      // Equal-Height Vertical Ruler (`I--- H: 188px (与 N 张卡片等高) ---I`)",
  "      if (matchedHeightCards.length > 0) {",
  "        const rx = sx + finalW + 16;",
  "        const midY = sy + finalH / 2;",
  "        parts.push(`",
  "          <line class=\"vs-size-ruler\" x1=\"${rx}\" y1=\"${sy}\" x2=\"${rx}\" y2=\"${sy + finalH}\"></line>",
  "          <line class=\"vs-size-ruler\" x1=\"${rx - 5}\" y1=\"${sy}\" x2=\"${rx + 5}\" y2=\"${sy}\"></line>",
  "          <line class=\"vs-size-ruler\" x1=\"${rx - 5}\" y1=\"${sy + finalH}\" x2=\"${rx + 5}\" y2=\"${sy + finalH}\"></line>",
  "        `);",
  "        const labelTxt = `H: ${finalH}px · 与 ${matchedHeightCards.length} 张等高`;",
  "        const pillW = labelTxt.length * 6.8 + 16;",
  "        parts.push(`",
  "          <rect x=\"${rx + 8}\" y=\"${midY - 10}\" width=\"${pillW}\" height=\"19\" rx=\"5\" fill=\"#e11d48\"></rect>",
  "          <text class=\"vs-ruler-label\" x=\"${rx + 8 + pillW / 2}\" y=\"${midY + 3}\" text-anchor=\"middle\">${esc(labelTxt)}</text>",
  "        `);",
  "        // Highlight reference height rulers on every matched sibling card!",
  "        matchedHeightCards.forEach((mc) => {",
  "          const mrx = mc.right + 9;",
  "          parts.push(`",
  "            <line class=\"vs-size-match-ref\" x1=\"${mrx}\" y1=\"${mc.y}\" x2=\"${mrx}\" y2=\"${mc.bottom}\"></line>",
  "            <line class=\"vs-size-match-ref\" x1=\"${mrx - 4}\" y1=\"${mc.y}\" x2=\"${mrx + 4}\" y2=\"${mc.y}\"></line>",
  "            <line class=\"vs-size-match-ref\" x1=\"${mrx - 4}\" y1=\"${mc.bottom}\" x2=\"${mrx + 4}\" y2=\"${mc.bottom}\"></line>",
  "          `);",
  "        });",
  "      }",
  "",
  "      if (svg) svg.innerHTML = parts.join('');",
  "      return { w: finalW, h: finalH };",
  "    }",
  "",
  "    function computeMoveWithVsSnap(movingIdsSet, leadId, rawX, rawY) {",
  "      const nodes = getActiveNodesList();",
  "      const leadEl = document.getElementById(`card-${leadId}`);",
  "      if (!leadEl) return { x: rawX, y: rawY };",
  "      const w = leadEl.offsetWidth;",
  "      const h = leadEl.offsetHeight;",
  "",
  "      const TOL = 6;",
  "      let snapX = rawX;",
  "      let snapY = rawY;",
  "      const lines = [];",
  "",
  "      nodes.forEach((n) => {",
  "        if (movingIdsSet.has(n.id)) return;",
  "        const el = document.getElementById(`card-${n.id}`);",
  "        if (!el) return;",
  "        const ox = el.offsetLeft;",
  "        const oy = el.offsetTop;",
  "        const ow = el.offsetWidth;",
  "        const oh = el.offsetHeight;",
  "",
  "        if (Math.abs(rawX - ox) <= TOL) {",
  "          snapX = ox;",
  "          lines.push(`<line class=\"vs-align-line\" x1=\"${ox}\" y1=\"${Math.min(rawY, oy) - 12}\" x2=\"${ox}\" y2=\"${Math.max(rawY + h, oy + oh) + 12}\"></line>`);",
  "        } else if (Math.abs((rawX + w) - (ox + ow)) <= TOL) {",
  "          snapX = ox + ow - w;",
  "          lines.push(`<line class=\"vs-align-line\" x1=\"${ox + ow}\" y1=\"${Math.min(rawY, oy) - 12}\" x2=\"${ox + ow}\" y2=\"${Math.max(rawY + h, oy + oh) + 12}\"></line>`);",
  "        }",
  "",
  "        if (Math.abs(rawY - oy) <= TOL) {",
  "          snapY = oy;",
  "          lines.push(`<line class=\"vs-align-line\" x1=\"${Math.min(snapX, ox) - 12}\" y1=\"${oy}\" x2=\"${Math.max(snapX + w, ox + ow) + 12}\" y2=\"${oy}\"></line>`);",
  "        } else if (Math.abs((rawY + h) - (oy + oh)) <= TOL) {",
  "          snapY = oy + oh - h;",
  "          lines.push(`<line class=\"vs-align-line\" x1=\"${Math.min(snapX, ox) - 12}\" y1=\"${oy + oh}\" x2=\"${Math.max(snapX + w, ox + ow) + 12}\" y2=\"${oy + oh}\"></line>`);",
  "        }",
  "      });",
  "",
  "      const svg = document.getElementById('snaplines-svg');",
  "      if (svg) svg.innerHTML = lines.join('');",
  "      return { x: snapX, y: snapY };",
  "    }",
  "",
  "    // ============================================================================"
  ].join('\n');
}
