// 画布外文本、组合框标题与卡片标题原地双击重命名及防重绘连击检测模块
export function buildWbInlineRename() {
  return [
  "    function setupInlineRenameEvents() {",
  "      // Handle single-click & double-click on [data-sel-text] outside #canvas-stage (header, left drawer, right header)",
  "      document.addEventListener('dblclick', (e) => {",
  "        if (e.target.closest('#canvas-stage')) return;",
  "        const chromeTxt = e.target.closest('[data-sel-text]');",
  "        if (chromeTxt) {",
  "          e.stopPropagation();",
  "          e.preventDefault();",
  "          startInlineRenameOnTextEl(chromeTxt);",
  "        }",
  "      });",
  "",
  "      document.addEventListener('focusout', (e) => {",
  "        const gInp = e.target.closest('[data-group-input]');",
  "        if (gInp && state.editingGroupId) {",
  "          const gid = gInp.getAttribute('data-group-input');",
  "          const grp = getActiveGroupsList().find((g) => g.id === gid);",
  "          if (grp && gInp.value.trim()) grp.title = gInp.value.trim();",
  "          state.editingGroupId = null;",
  "          renderAll();",
  "          return;",
  "        }",
  "        const cInp = e.target.closest('[data-card-title-input]');",
  "        if (cInp && state.editingCardTitleId) {",
  "          const nid = cInp.getAttribute('data-card-title-input');",
  "          const nd = getActiveNodesList().find((n) => n.id === nid);",
  "          if (nd && cInp.value.trim()) nd.title = cInp.value.trim();",
  "          state.editingCardTitleId = null;",
  "          renderAll();",
  "          return;",
  "        }",
  "        const tInp = e.target.closest('[data-inline-sel-input]');",
  "        if (tInp) {",
  "          const key = tInp.getAttribute('data-inline-sel-input');",
  "          if (tInp.value.trim()) applyTextRenameByKey(key, tInp.value.trim());",
  "          renderAll();",
  "        }",
  "      });",
  "",
  "      document.addEventListener('keydown', (e) => {",
  "        const gInp = e.target.closest('[data-group-input]');",
  "        if (gInp) {",
  "          if (e.key === 'Enter') {",
  "            e.preventDefault();",
  "            const gid = gInp.getAttribute('data-group-input');",
  "            const grp = getActiveGroupsList().find((g) => g.id === gid);",
  "            if (grp && gInp.value.trim()) grp.title = gInp.value.trim();",
  "            state.editingGroupId = null;",
  "            renderAll();",
  "            showToast('已更新组合框标题');",
  "          } else if (e.key === 'Escape') {",
  "            e.preventDefault();",
  "            e.stopPropagation();",
  "            state.editingGroupId = null;",
  "            renderAll();",
  "          }",
  "          return;",
  "        }",
  "        const cInp = e.target.closest('[data-card-title-input]');",
  "        if (cInp) {",
  "          if (e.key === 'Enter') {",
  "            e.preventDefault();",
  "            const nid = cInp.getAttribute('data-card-title-input');",
  "            const nd = getActiveNodesList().find((n) => n.id === nid);",
  "            if (nd && cInp.value.trim()) nd.title = cInp.value.trim();",
  "            state.editingCardTitleId = null;",
  "            renderAll();",
  "            showToast('已修改卡片名称');",
  "          } else if (e.key === 'Escape') {",
  "            e.preventDefault();",
  "            e.stopPropagation();",
  "            state.editingCardTitleId = null;",
  "            renderAll();",
  "          }",
  "          return;",
  "        }",
  "        const tInp = e.target.closest('[data-inline-sel-input]');",
  "        if (tInp) {",
  "          if (e.key === 'Enter') {",
  "            e.preventDefault();",
  "            const key = tInp.getAttribute('data-inline-sel-input');",
  "            if (tInp.value.trim()) {",
  "              applyTextRenameByKey(key, tInp.value.trim());",
  "              showToast(`已重命名为「${tInp.value.trim()}」`);",
  "            }",
  "            renderAll();",
  "          } else if (e.key === 'Escape') {",
  "            e.preventDefault();",
  "            e.stopPropagation();",
  "            renderAll();",
  "          }",
  "        }",
  "      });",
  "",
  "    }",
  "",
  "      // Bulletproof double-press detector so double-clicking unselected group header or card title ALWAYS enters edit mode even across re-render!",
  "      (function attachFastDoublePressRename() {",
  "        let lastDown = { key: '', time: 0, x: 0, y: 0 };",
  "        document.addEventListener('pointerdown', (e) => {",
  "          if (e.button !== 0 || isSandboxReadOnly()) return;",
  "          if (e.target.closest('button, input')) return;",
  "          const grpHit = e.target.closest('[data-group-title], [data-drag-group]');",
  "          const cardTitleHit = e.target.closest('[data-card-title]');",
  "          let key = '';",
  "          if (grpHit) {",
  "            const gid = grpHit.getAttribute('data-group-title') || grpHit.getAttribute('data-drag-group');",
  "            key = `grp:${gid}`;",
  "          } else if (cardTitleHit) {",
  "            key = `ctitle:${cardTitleHit.getAttribute('data-card-title')}`;",
  "          }",
  "          if (!key) { lastDown = { key: '', time: 0, x: 0, y: 0 }; return; }",
  "          const now = Date.now();",
  "          const dist = Math.hypot(e.clientX - lastDown.x, e.clientY - lastDown.y);",
  "          if (lastDown.key === key && (now - lastDown.time) < 360 && dist <= 7) {",
  "            lastDown = { key: '', time: 0, x: 0, y: 0 };",
  "            e.preventDefault();",
  "            e.stopPropagation();",
  "            if (key.startsWith('grp:')) {",
  "              state.editingGroupId = key.slice(4);",
  "              state.selectedGroupId = state.editingGroupId;",
  "              state.selectedNodeIds.clear();",
  "              renderAll();",
  "            } else if (key.startsWith('ctitle:')) {",
  "              state.editingCardTitleId = key.slice(7);",
  "              renderAll();",
  "            }",
  "          } else {",
  "            lastDown = { key, time: now, x: e.clientX, y: e.clientY };",
  "          }",
  "        }, true);",
  "      })();",
  "",
  "    // Boot sequence handled by ui-shell.mjs after ATLAS hydration"
  ].join('\n');
}
