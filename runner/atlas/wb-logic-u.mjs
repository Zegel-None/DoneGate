// 工作台交互逻辑分片 U（零外网依赖单文件工作台分片模块，严格 <= 300 行）
export function buildWbLogicU() {
  return [
  "          renderAll();",
  "          return;",
  "        }",
  "",
  "        const grpHeadOrTitle = e.target.closest('[data-group-title], [data-drag-group]');",
  "        if (grpHeadOrTitle && !isSandboxReadOnly()) {",
  "          e.stopPropagation();",
  "          e.preventDefault();",
  "          const gid = grpHeadOrTitle.getAttribute('data-group-title') || grpHeadOrTitle.getAttribute('data-drag-group');",
  "          state.selectedGroupId = gid;",
  "          state.selectedNodeIds.clear();",
  "          state.editingGroupId = gid;",
  "          renderAll();",
  "          return;",
  "        }",
  "",
  "        const sgCard = e.target.closest('[data-is-subgraph=\"1\"]');",
  "        if (sgCard && !e.target.closest('button, a')) {",
  "          enterSubgraphNode(sgCard.getAttribute('data-card-id'));",
  "          return;",
  "        }",
  "",
  "        const subCard = e.target.closest('[data-subrepo-id]');",
  "        if (subCard && subCard.getAttribute('data-subrepo-id')) {",
  "          drillIntoSubRepo(subCard.getAttribute('data-subrepo-id'));",
  "          return;",
  "        }",
  "",
  "        if (!e.target.closest('[data-card-id], button')) {",
  "          const wr = document.getElementById('canvas-world').getBoundingClientRect();",
  "          state.ctxWorldPos = {",
  "            x: Math.round((e.clientX - wr.left) / state.zoom - 110),",
  "            y: Math.round((e.clientY - wr.top) / state.zoom - 20)",
  "          };",
  "          openCanvasCascadingMenu(e.clientX, e.clientY);",
  "        }",
  "      });",
  "",
  "      window.addEventListener('pointermove', (e) => {",
  "        lastPtrX = e.clientX;",
  "        lastPtrY = e.clientY;",
  "        if (panDrag) {",
  "          state.panX = panDrag.origX + (e.clientX - panDrag.startX);",
  "          state.panY = panDrag.origY + (e.clientY - panDrag.startY);",
  "          applyViewportTransform();",
  "          return;",
  "        }",
  "        if (groupDrag || cardDrag) {",
  "          ensureEdgeAutoPanRunning(e.clientX, e.clientY);",
  "          applyCardOrGroupDragAt(e.clientX, e.clientY);",
  "          return;",
  "        }",
  "        if (wireDrag) {",
  "          ensureEdgeAutoPanRunning(e.clientX, e.clientY);",
  "          const wr = document.getElementById('canvas-world').getBoundingClientRect();",
  "          const x2 = (e.clientX - wr.left) / state.zoom;",
  "          const y2 = (e.clientY - wr.top) / state.zoom;",
  "          const hp = e.target.closest('[data-port-dir]');",
  "          renderWires({ ...wireDrag, x2, y2, hoverNode: hp ? hp.getAttribute('data-port-node') : null });",
  "          return;",
  "        }",
  "        if (boxSelect) {",
  "          marquee.style.left = `${Math.min(boxSelect.startX, e.clientX)}px`;",
  "          marquee.style.top = `${Math.min(boxSelect.startY, e.clientY)}px`;",
  "          marquee.style.width = `${Math.abs(e.clientX - boxSelect.startX)}px`;",
  "          marquee.style.height = `${Math.abs(e.clientY - boxSelect.startY)}px`;",
  "        }",
  "      });",
  "",
  "      stage.addEventListener('wheel', (e) => {",
  "        const scrollWin = !e.ctrlKey && !e.metaKey ? e.target.closest('.card-scroll-window') : null;",
  "        if (scrollWin && scrollWin.scrollHeight > scrollWin.clientHeight + 1) {",
  "          const atTop = scrollWin.scrollTop <= 0 && e.deltaY < 0;",
  "          const atBot = scrollWin.scrollTop + scrollWin.clientHeight >= scrollWin.scrollHeight - 1 && e.deltaY > 0;",
  "          if (!atTop && !atBot) {",
  "            e.stopPropagation();",
  "            return;",
  "          }",
  "        }",
  "        e.preventDefault();",
  "        const rect = stage.getBoundingClientRect();",
  "        const factor = e.deltaY < 0 ? 1.08 : 0.92;",
  "        const nextZ = Math.min(1.85, Math.max(0.4, state.zoom * factor));",
  "        const px = e.clientX - rect.left;",
  "        const py = e.clientY - rect.top;",
  "        const wx = (px - state.panX) / state.zoom;",
  "        const wy = (py - state.panY) / state.zoom;",
  "        state.zoom = nextZ;",
  "        state.panX = px - wx * nextZ;",
  "        state.panY = py - wy * nextZ;",
  "        applyViewportTransform();",
  "      }, { passive: false });",
  "",
  "      const leftDrawer = document.getElementById('left-drawer');",
  "      leftDrawer.addEventListener('dragstart', (e) => {",
  "        const pkEl = e.target.closest('[data-drag-pack]');",
  "        if (pkEl) packDragId = pkEl.getAttribute('data-drag-pack');",
  "      });",
  "      leftDrawer.addEventListener('dragover', (e) => {",
  "        if (e.target.closest('[data-drop-pack-grp]')) e.preventDefault();",
  "      });",
  "      leftDrawer.addEventListener('drop', (e) => {",
  "        const z = e.target.closest('[data-drop-pack-grp]');",
  "        if (z && packDragId && WORKFLOW_PACKS[packDragId]) {",
  "          WORKFLOW_PACKS[packDragId].group = z.getAttribute('data-drop-pack-grp');",
  "          packDragId = null;",
  "          renderLeftDrawer();",
  "          showToast('已更新开发包分组');",
  "        }",
  "      });",
  "",
  "      // Capture-phase button tracker: clicking ANY UI button treats it as the selected button in Subagent!",
  "      document.addEventListener('click', (e) => {",
  "        const hitBtn = e.target.closest('button');",
  "        if (!hitBtn) return;",
  "        const desc = identifyControlElement(hitBtn);",
  "        if (desc) {",
  "          state.lastClickedControl = desc;",
  "          state.activeFocusTarget = 'control';",
  "          requestAnimationFrame(() => {",
  "            renderRightSidebar();",
  "            applyAllControlStyleOverrides();",
  "          });",
  "        }",
  "      }, true);",
  "",
  "      // Handle single-click & double-click on [data-sel-text] outside #canvas-stage (header, left drawer, right header)",
  "      document.addEventListener('dblclick', (e) => {",
  "        if (e.target.closest('#canvas-stage')) return;",
  "        const chromeTxt = e.target.closest('[data-sel-text]');",
  "        if (chromeTxt) {",
  "          e.stopPropagation();",
  "          e.preventDefault();",
  "          startInlineRenameOnTextEl(chromeTxt);",
  "        }",
  "      });",
  "",
  "      document.addEventListener('focusout', (e) => {",
  "        const gInp = e.target.closest('[data-group-input]');",
  "        if (gInp && state.editingGroupId) {",
  "          const gid = gInp.getAttribute('data-group-input');",
  "          const grp = getActiveGroupsList().find((g) => g.id === gid);",
  "          if (grp && gInp.value.trim()) grp.title = gInp.value.trim();",
  "          state.editingGroupId = null;",
  "          renderAll();",
  "          return;",
  "        }",
  "        const cInp = e.target.closest('[data-card-title-input]');",
  "        if (cInp && state.editingCardTitleId) {",
  "          const nid = cInp.getAttribute('data-card-title-input');",
  "          const nd = getActiveNodesList().find((n) => n.id === nid);",
  "          if (nd && cInp.value.trim()) nd.title = cInp.value.trim();",
  "          state.editingCardTitleId = null;",
  "          renderAll();",
  "          return;",
  "        }",
  "        const tInp = e.target.closest('[data-inline-sel-input]');",
  "        if (tInp) {",
  "          const key = tInp.getAttribute('data-inline-sel-input');",
  "          if (tInp.value.trim()) applyTextRenameByKey(key, tInp.value.trim());",
  "          renderAll();",
  "        }",
  "      });",
  "",
  "      document.addEventListener('keydown', (e) => {",
  "        const gInp = e.target.closest('[data-group-input]');",
  "        if (gInp) {",
  "          if (e.key === 'Enter') {",
  "            e.preventDefault();",
  "            const gid = gInp.getAttribute('data-group-input');",
  "            const grp = getActiveGroupsList().find((g) => g.id === gid);",
  "            if (grp && gInp.value.trim()) grp.title = gInp.value.trim();",
  "            state.editingGroupId = null;",
  "            renderAll();",
  "            showToast('已更新组合框标题');",
  "          } else if (e.key === 'Escape') {",
  "            e.preventDefault();",
  "            e.stopPropagation();",
  "            state.editingGroupId = null;",
  "            renderAll();",
  "          }",
  "          return;",
  "        }",
  "        const cInp = e.target.closest('[data-card-title-input]');",
  "        if (cInp) {",
  "          if (e.key === 'Enter') {",
  "            e.preventDefault();",
  "            const nid = cInp.getAttribute('data-card-title-input');",
  "            const nd = getActiveNodesList().find((n) => n.id === nid);",
  "            if (nd && cInp.value.trim()) nd.title = cInp.value.trim();",
  "            state.editingCardTitleId = null;",
  "            renderAll();",
  "            showToast('已修改卡片名称');",
  "          } else if (e.key === 'Escape') {",
  "            e.preventDefault();",
  "            e.stopPropagation();",
  "            state.editingCardTitleId = null;",
  "            renderAll();",
  "          }",
  "          return;",
  "        }",
  "        const tInp = e.target.closest('[data-inline-sel-input]');",
  "        if (tInp) {",
  "          if (e.key === 'Enter') {",
  "            e.preventDefault();",
  "            const key = tInp.getAttribute('data-inline-sel-input');",
  "            if (tInp.value.trim()) {",
  "              applyTextRenameByKey(key, tInp.value.trim());",
  "              showToast(`已重命名为「${tInp.value.trim()}」`);",
  "            }",
  "            renderAll();",
  "          } else if (e.key === 'Escape') {",
  "            e.preventDefault();",
  "            e.stopPropagation();",
  "            renderAll();",
  "          }",
  "        }",
  "      });",
  "",
  "      document.addEventListener('click', (e) => {",
  "        if (!e.target.closest('#ctx-root-menu, #ctx-sub-menu')) closeCascadingMenus();",
  "",
  "        // Single-click on selectable pure text outside canvas-stage (header / sidebars)",
  "        if (!e.target.closest('#canvas-stage') && !e.target.closest('button, input')) {",
  "          const chromeTxt = e.target.closest('[data-sel-text]');",
  "          if (chromeTxt) {",
  "            const key = chromeTxt.getAttribute('data-sel-text');",
  "            state.selectedTextItem = describeSelectableTextByKey(key, chromeTxt);",
  "            state.activeFocusTarget = 'text';",
  "            applyAllTextOverridesAndSelection();",
  "            renderRightSidebar();",
  "            return;",
  "          }",
  "        }",
  "",
  "        const railTabBtn = e.target.closest('[data-rail-tab]');",
  "        if (railTabBtn) {",
  "          const tab = railTabBtn.getAttribute('data-rail-tab');",
  "          const clickedInRail = Boolean(railTabBtn.closest('#left-icon-rail'));",
  "          if (clickedInRail && state.leftOpen && state.leftTab === tab) {",
  "            state.leftOpen = false;",
  "            renderLeftDrawer();",
  "            return;",
  "          }",
  "          state.leftOpen = true;"
  ].join('\n');
}
