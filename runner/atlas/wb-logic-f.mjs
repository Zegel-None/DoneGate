// 工作台交互逻辑分片 F（零外网依赖单文件工作台分片模块，严格 <= 300 行）
export function buildWbLogicF() {
  return [
  "        adj.set(n.id, []);",
  "        undir.set(n.id, new Set());",
  "        indeg.set(n.id, 0);",
  "        parentsMap.set(n.id, []);",
  "      });",
  "",
  "      const addEdge = (u, v) => {",
  "        if (u === v || !adj.has(u) || !adj.has(v)) return;",
  "        if (!adj.get(u).includes(v)) {",
  "          adj.get(u).push(v);",
  "          indeg.set(v, (indeg.get(v) || 0) + 1);",
  "          parentsMap.get(v).push(u);",
  "        }",
  "        undir.get(u).add(v);",
  "        undir.get(v).add(u);",
  "      };",
  "",
  "      if (state.page === 'workshop') {",
  "        getActiveWorkshopGraph().links.forEach((lk) => addEdge(lk.fromNode, lk.toNode));",
  "      } else {",
  "        nodes.forEach((src) => (src.nextIds || []).forEach((tid) => addEdge(src.id, tid)));",
  "      }",
  "",
  "      const visitedComp = new Set();",
  "      const components = [];",
  "      nodes.forEach((n) => {",
  "        if (visitedComp.has(n.id)) return;",
  "        const comp = [];",
  "        const q = [n.id];",
  "        visitedComp.add(n.id);",
  "        while (q.length) {",
  "          const cur = q.shift();",
  "          const cNode = nodes.find((item) => item.id === cur);",
  "          if (cNode) comp.push(cNode);",
  "          (undir.get(cur) || []).forEach((nb) => {",
  "            if (!visitedComp.has(nb)) { visitedComp.add(nb); q.push(nb); }",
  "          });",
  "        }",
  "        components.push(comp);",
  "      });",
  "",
  "      function buildTopoStages(subList) {",
  "        const subIds = new Set(subList.map((n) => n.id));",
  "        const colOf = new Map();",
  "        const rem = new Set(subIds);",
  "        const wIndeg = new Map();",
  "        subList.forEach((n) => {",
  "          const deg = (parentsMap.get(n.id) || []).filter((p) => subIds.has(p)).length;",
  "          wIndeg.set(n.id, deg);",
  "        });",
  "",
  "        let guard = 0;",
  "        while (rem.size > 0 && guard++ < 200) {",
  "          let ready = [...rem].filter((id) => (wIndeg.get(id) || 0) <= 0);",
  "          if (!ready.length) {",
  "            ready = [[...rem].sort((a, b) => {",
  "              const na = subList.find((n) => n.id === a);",
  "              const nb = subList.find((n) => n.id === b);",
  "              return (na ? na.x : 0) - (nb ? nb.x : 0);",
  "            })[0]];",
  "          }",
  "          ready.forEach((uid) => {",
  "            rem.delete(uid);",
  "            const uNode = subList.find((n) => n.id === uid);",
  "            const pCols = (parentsMap.get(uid) || []).filter((p) => colOf.has(p)).map((p) => colOf.get(p));",
  "            let c = pCols.length ? Math.max(...pCols) + 1 : 0;",
  "            if (uNode && uNode.isBoundary === 'in') c = 0;",
  "            colOf.set(uid, c);",
  "            (adj.get(uid) || []).filter((v) => subIds.has(v)).forEach((vid) => {",
  "              wIndeg.set(vid, (wIndeg.get(vid) || 1) - 1);",
  "            });",
  "          });",
  "        }",
  "        const maxC = Math.max(0, ...colOf.values());",
  "        subList.forEach((n) => { if (n.isBoundary === 'out') colOf.set(n.id, maxC + 1); });",
  "",
  "        const buckets = new Map();",
  "        subList.forEach((n) => {",
  "          const c = colOf.get(n.id) || 0;",
  "          if (!buckets.has(c)) buckets.set(c, []);",
  "          buckets.get(c).push(n);",
  "        });",
  "        const cols = [...buckets.keys()].sort((a, b) => a - b);",
  "        const tempOrder = new Map();",
  "        subList.forEach((n) => tempOrder.set(n.id, n.y));",
  "        cols.forEach((c) => {",
  "          const list = buckets.get(c);",
  "          list.sort((a, b) => {",
  "            const pa = (parentsMap.get(a.id) || []).filter((p) => tempOrder.has(p));",
  "            const pb = (parentsMap.get(b.id) || []).filter((p) => tempOrder.has(p));",
  "            const ya = pa.length ? pa.reduce((s, p) => s + tempOrder.get(p), 0) / pa.length : a.y;",
  "            const yb = pb.length ? pb.reduce((s, p) => s + tempOrder.get(p), 0) / pb.length : b.y;",
  "            return ya - yb;",
  "          });",
  "          list.forEach((n, idx) => tempOrder.set(n.id, idx * 100));",
  "        });",
  "        return cols.map((c) => buckets.get(c));",
  "      }",
  "",
  "      const startX = isSubset ? origMinX : 56;",
  "      const startY = isSubset ? origMinY : 68;",
  "",
  "      if (mode === 'topo') {",
  "        const stages = buildTopoStages(nodes);",
  "        const colGapX = isSubset ? 62 : 84;",
  "        const rowGapY = isSubset ? 34 : 40;",
  "        let curX = startX;",
  "        const colHeights = [];",
  "",
  "        stages.forEach((list, idx) => {",
  "          let colMaxW = 190;",
  "          let curY = 0;",
  "          list.forEach((n) => {",
  "            const m = measured.get(n.id);",
  "            colMaxW = Math.max(colMaxW, m.w);",
  "            n.x = curX;",
  "            n._relY = curY;",
  "            curY += m.h + rowGapY;",
  "          });",
  "          colHeights[idx] = Math.max(0, curY - rowGapY);",
  "          curX += colMaxW + colGapX;",
  "        });",
  "",
  "        const tallest = Math.max(140, ...colHeights);",
  "        stages.forEach((list, idx) => {",
  "          const topOff = startY + Math.round((tallest - colHeights[idx]) / 2);",
  "          list.forEach((n) => {",
  "            n.y = topOff + n._relY;",
  "            delete n._relY;",
  "          });",
  "        });",
  "      } else if (mode === 'horiz') {",
  "        const colGapX = 52;",
  "        const rowGapY = 28;",
  "        let curX = startX;",
  "        components.forEach((comp) => {",
  "          const stages = buildTopoStages(comp);",
  "          stages.forEach((list) => {",
  "            let colMaxW = 180;",
  "            let curY = startY;",
  "            list.forEach((n) => {",
  "              const m = measured.get(n.id);",
  "              colMaxW = Math.max(colMaxW, m.w);",
  "              n.x = curX;",
  "              n.y = curY;",
  "              curY += m.h + rowGapY;",
  "            });",
  "            curX += colMaxW + colGapX;",
  "          });",
  "        });",
  "      } else if (mode === 'vert') {",
  "        const colGapX = 42;",
  "        const rowGapY = 42;",
  "        const allStages = [];",
  "        components.forEach((comp) => {",
  "          buildTopoStages(comp).forEach((st) => allStages.push(st));",
  "        });",
  "",
  "        const rowWidths = allStages.map((list) =>",
  "          list.reduce((sum, n) => sum + measured.get(n.id).w, 0) + Math.max(0, list.length - 1) * colGapX",
  "        );",
  "        const maxRowW = Math.max(252, ...rowWidths);",
  "        const centerAxisX = startX + Math.round(maxRowW / 2);",
  "",
  "        let curY = startY;",
  "        allStages.forEach((list, idx) => {",
  "          const rw = rowWidths[idx];",
  "          let curX = Math.max(28, Math.round(centerAxisX - rw / 2));",
  "          let rowMaxH = 80;",
  "          list.forEach((n) => {",
  "            const m = measured.get(n.id);",
  "            n.x = curX;",
  "            n.y = curY;",
  "            curX += m.w + colGapX;",
  "            rowMaxH = Math.max(rowMaxH, m.h);",
  "          });",
  "          curY += rowMaxH + rowGapY;",
  "        });",
  "      } else if (mode === 'snake') {",
  "        const ordered = [];",
  "        components.forEach((comp) => {",
  "          buildTopoStages(comp).forEach((st) => st.forEach((n) => ordered.push(n)));",
  "        });",
  "",
  "        const N = ordered.length;",
  "        const gapX = 52;",
  "        const gapY = 42;",
  "        let bestK = Math.max(1, Math.min(N, 2));",
  "        let bestScore = Infinity;",
  "",
  "        for (let k = 1; k <= N; k++) {",
  "          if (N >= 3 && k === N) continue;",
  "          const numRows = Math.ceil(N / k);",
  "          const colW = new Array(k).fill(0);",
  "          const rowH = new Array(numRows).fill(0);",
  "",
  "          ordered.forEach((n, i) => {",
  "            const r = Math.floor(i / k);",
  "            const c = (r % 2 === 0) ? (i % k) : (k - 1 - (i % k));",
  "            const m = measured.get(n.id);",
  "            colW[c] = Math.max(colW[c], m.w);",
  "            rowH[r] = Math.max(rowH[r], m.h);",
  "          });",
  "",
  "          const totalW = colW.reduce((a, b) => a + b, 0) + Math.max(0, k - 1) * gapX;",
  "          const totalH = rowH.reduce((a, b) => a + b, 0) + Math.max(0, numRows - 1) * gapY;",
  "          const aspect = Math.max(totalW / Math.max(1, totalH), totalH / Math.max(1, totalW));",
  "          const score = aspect + (totalW + totalH) * 0.00015;",
  "          if (score < bestScore) {",
  "            bestScore = score;",
  "            bestK = k;",
  "          }",
  "        }",
  "",
  "        const numRows = Math.ceil(N / bestK);",
  "        const colW = new Array(bestK).fill(0);",
  "        const rowH = new Array(numRows).fill(0);",
  "        ordered.forEach((n, i) => {",
  "          const r = Math.floor(i / bestK);",
  "          const c = (r % 2 === 0) ? (i % bestK) : (bestK - 1 - (i % bestK));",
  "          const m = measured.get(n.id);",
  "          colW[c] = Math.max(colW[c], m.w);",
  "          rowH[r] = Math.max(rowH[r], m.h);",
  "        });",
  "",
  "        const colX = [];",
  "        let accX = startX;",
  "        for (let c = 0; c < bestK; c++) {",
  "          colX[c] = accX;",
  "          accX += colW[c] + gapX;",
  "        }",
  "        const rowY = [];",
  "        let accY = startY;",
  "        for (let r = 0; r < numRows; r++) {",
  "          rowY[r] = accY;",
  "          accY += rowH[r] + gapY;",
  "        }",
  "",
  "        ordered.forEach((n, i) => {",
  "          const r = Math.floor(i / bestK);",
  "          const c = (r % 2 === 0) ? (i % bestK) : (bestK - 1 - (i % bestK));",
  "          n.x = colX[c];",
  "          n.y = rowY[r];",
  "        });",
  "      }"
  ].join('\n');
}
