  "              el.classList.toggle('is-selected', state.selectedNodeIds.has(el.getAttribute('data-card-id')));",
  "            });",
  "            renderRightSidebar();",
  "            renderSelectionFloatingToolbox();",
  "            renderWires(null);",
  "            return;",
  "          }",
  "          renderAll();",
  "",
  "          if (!isSandboxReadOnly() && e.target.closest('[data-drag-card]') && !e.target.closest('button, a')) {",
  "            const nodes = getActiveNodesList();",
  "            const origins = new Map();",
  "            state.selectedNodeIds.forEach((id) => {",
  "              const obj = nodes.find((n) => n.id === id);",
  "              if (obj) origins.set(id, { x: obj.x, y: obj.y });",
