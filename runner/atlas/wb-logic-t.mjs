  "        if (e.target.closest('[data-stop-drag], .selection-toolbox, #drilldown-bar')) return;",
  "",
  "        // Loop pill: clicking loop text selects the wire (and tracks text if double-clicked); +/- buttons pass through to click",
  "        if (e.target.closest('.loop-pill')) {",
