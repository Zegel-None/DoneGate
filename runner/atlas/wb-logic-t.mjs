  "          if (lpWireEl && !e.target.closest('[data-action=\"loop-inc\"], [data-action=\"loop-dec\"]')) {",
  "            state.selectedLinkId = lpWireEl.getAttribute('data-link');",
  "            state.selectedNodeIds.clear();",
  "            state.selectedGroupId = null;",
  "            state.selectedTextItem = null;",
  "            state.activeFocusTarget = 'canvas';",
  "            renderWires(null);",
  "            renderSelectionFloatingToolbox();",
  "            renderRightSidebar();",
  "            document.querySelectorAll('.node-card.is-selected, .group-frame.is-selected').forEach((el) => el.classList.remove('is-selected'));",
  "            applyAllTextOverridesAndSelection();",
  "          }",
  "          return;",
  "        }",
  "",
  "        // Pure Selectable Text Inside Canvas (e.g.「承接 APK 产物」): single-click highlights without destroying DOM so dblclick always fires!",
  "        const selTextEl = e.target.closest('[data-sel-text]');",
  "        if (selTextEl && !e.ctrlKey && !e.metaKey) {",
  "          e.stopPropagation();",
  "          const key = selTextEl.getAttribute('data-sel-text');",
  "          state.selectedTextItem = describeSelectableTextByKey(key, selTextEl);",
  "          state.activeFocusTarget = 'text';",
  "          state.selectedNodeIds.clear();",
  "          state.selectedGroupId = null;",
  "          state.selectedLinkId = null;",
  "          state.colorPickerOpen = false;",
