  "            cardDrag = { startX: e.clientX, startY: e.clientY, origins };",
  "          }",
  "          return;",
  "        }",
  "",
  "        if (e.target.closest('button, input')) return;",
  "",
  "        const groupEl = e.target.closest('[data-group-id]');",
  "        if (groupEl && !(e.ctrlKey || e.metaKey)) {",
  "          const gid = groupEl.getAttribute('data-group-id');",
  "          state.selectedGroupId = gid;",
  "          state.selectedNodeIds.clear();",
  "          state.selectedLinkId = null;",
  "          state.activeFocusTarget = 'canvas';",
  "          renderAll();",
  "",
  "          if (!isSandboxReadOnly() && e.target.closest('[data-drag-group]')) {",
