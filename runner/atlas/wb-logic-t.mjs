  "        const resizeEl = e.target.closest('[data-resize-card]');",
  "        if (resizeEl) {",
  "          const nid = resizeEl.getAttribute('data-resize-card');",
  "          const obj = getActiveNodesList().find((n) => n.id === nid);",
