export function buildWbLogicV() {
  return [
  "          state.leftTab = tab;",
  "          if (tab === 'assets' && state.page !== 'sandbox') {",
  "            state.page = 'sandbox';",
  "            state.selectedGroupId = null;",
  "            state.selectedLinkId = null;",
  "            const nodes = getActiveNodesList();",
  "            state.selectedNodeIds = nodes[0] ? new Set([nodes[0].id]) : new Set();",
  "            renderAll();",
  "            requestAnimationFrame(fitCanvas);",
  "          } else if (tab === 'workflows' && state.page !== 'workshop') {",
  "            state.page = 'workshop';",
  "            state.selectedGroupId = null;",
  "            state.selectedLinkId = null;",
  "            const nodes = getActiveNodesList();",
  "            state.selectedNodeIds = nodes[0] ? new Set([nodes[0].id]) : new Set();",
  "            renderAll();",
  "            requestAnimationFrame(fitCanvas);",
  "          } else {",
  "            renderAll();",
  "          }",
  "          return;",
  "        }",
  "",
  "        const railSummon = e.target.closest('[data-rail-summon-tpl]');",
  "        if (railSummon) {",
  "          const tplId = railSummon.getAttribute('data-rail-summon-tpl');",
  "          if (state.page !== 'workshop') state.page = 'workshop';",
  "          const graph = getActiveWorkshopGraph();",
  "          const newId = 'n-' + Date.now();",
  "          const offset = (graph.nodes.length % 5) * 28;",
  "          const created = instantiateWorkshopNode(tplId, newId, 160 + offset, 120 + offset);",
  "          graph.nodes.push(created);",
  "          state.selectedNodeIds = new Set([newId]);",
  "          state.selectedGroupId = null;",
  "          state.selectedLinkId = null;",
  "          renderAll();",
  "          showToast(`已从节点库添加「${created.title}」`);",
  "          return;",
  "        }",
  "",
  "        const swFocus = e.target.closest('[data-switch-focus]');",
  "        if (swFocus) {",
  "          state.activeFocusTarget = swFocus.getAttribute('data-switch-focus');",
  "          renderRightSidebar();",
  "          document.getElementById('agent-input')?.focus();",
  "          return;",
  "        }",
  "",
  "        const pickColorBtn = e.target.closest('[data-pick-color]');",
  "        if (pickColorBtn) {",
  "          e.stopPropagation();",
  "          const cKey = pickColorBtn.getAttribute('data-pick-color');",
  "          if (state.selectedGroupId && state.selectedNodeIds.size === 0) {",
  "            const grp = getActiveGroupsList().find((g) => g.id === state.selectedGroupId);",
  "            if (grp) grp.colorKey = cKey === 'none' ? 'blue' : cKey;",
  "          } else {",
  "            const nodes = getActiveNodesList();",
  "            nodes.forEach((n) => {",
  "              if (state.selectedNodeIds.has(n.id) && !n.isBoundary) {",
  "                n.colorKey = cKey === 'none' ? null : cKey;",
  "              }",
  "            });",
  "          }",
  "          state.colorPickerOpen = false;",
  "          renderAll();",
  "          const entry = getPaletteEntry(cKey);",
  "          showToast(`已应用颜色：${entry.name}`);",
  "          return;",
  "        }",
  "",
  "        const packCtx = e.target.closest('[data-pack-ctx]');",
  "        if (packCtx) {",
  "          const cmd = packCtx.getAttribute('data-pack-ctx');",
  "          const pid = packCtx.getAttribute('data-pack');",
  "          closeCascadingMenus();",
  "          if (cmd === 'provision-deps') triggerProvisionWorkflowDeps(pid);",
  "          else if (cmd === 'inspect-deps') syncAllWorkflowDepsFromBackend(pid);",
  "          else if (cmd === 'open-deps-dir') {",
  "            const safeId = String(pid || 'default').replace(/[^a-zA-Z0-9._-]/g, '_');",
  "            openFolderViaBackend(`workflows/.deps/${safeId}`);",
  "          } else if (cmd === 'quote-pack' && typeof emitDshQuote === 'function') {",
  "            const pk = WORKFLOW_PACKS[pid];",
  "            const safeId = String(pid || 'default').replace(/[^a-zA-Z0-9._-]/g, '_');",
  "            emitDshQuote(buildDshQuoteTarget({ kind: 'group', id: pid, title: (pk && pk.name) || pid, scopes: [`workflows/.deps/${safeId}/`], desc: `开发流方案包「${(pk && pk.name) || pid}」` }));",
  "          }",
  "          return;",
  "        }",
  "",
  "        const grpCtx = e.target.closest('[data-group-ctx]');",
  "        if (grpCtx) {",
  "          const cmd = grpCtx.getAttribute('data-group-ctx');",
  "          const gid = grpCtx.getAttribute('data-group');",
  "          closeCascadingMenus();",
  "          if (cmd === 'to-subgraph') convertGroupToSubgraph(gid);",
  "          else if (cmd === 'rename') { state.editingGroupId = gid; renderAll(); }",
  "          else if (cmd === 'tidy-group') {",
  "            const grp = getActiveGroupsList().find((g) => g.id === gid);",
  "            if (grp) autoArrangeNodesSubset(new Set(grp.memberIds));",
  "          } else if (cmd === 'ungroup') ungroupById(gid);",
  "          return;",
  "        }",
  "",
  "        const cardCtx = e.target.closest('[data-card-ctx]');",
  "        if (cardCtx) {",
  "          const cmd = cardCtx.getAttribute('data-card-ctx');",
  "          const nid = cardCtx.getAttribute('data-node');",
  "          closeCascadingMenus();",
  "          if (cmd === 'tidy-selected') autoArrangeNodesSubset(state.selectedNodeIds);",
  "          else if (cmd === 'group-selected') createGroupFromSelection();",
  "          else if (cmd === 'merge-selected') mergeSelectedIntoSubgraph();",
  "          else if (cmd === 'sg-to-group') convertSubgraphToGroup(nid);",
  "          else if (cmd === 'open-folder') showOpenInFolderModal(nid);",
  "          else if (cmd === 'enter-sg') enterSubgraphNode(nid);",
  "          else if (cmd === 'bypass') toggleSelectedBypass();",
  "          else if (cmd === 'reset-size') {",
  "            const obj = getActiveNodesList().find((n) => n.id === nid);",
  "            if (obj) { obj.w = 252; obj.h = null; renderAll(); showToast('已恢复卡片默认尺寸'); }",
  "          } else if (cmd === 'copy') copySelectedNodeToClipboard();",
  "          else if (cmd === 'delete') deleteSelectedItems();",
  "          return;",
  "        }",
  "",
  "        const wireCtx = e.target.closest('[data-wire-ctx]');",
  "        if (wireCtx) {",
  "          const cmd = wireCtx.getAttribute('data-wire-ctx');",
  "          closeCascadingMenus();",
  "          if (cmd === 'explain') handleSubagentMessage('这条连线代表着什么数据传递？');",
  "          else if (cmd === 'disconnect') deleteSelectedItems();",
  "          return;",
  "        }",
  "",
  "        const copyPathBtn = e.target.closest('[data-copy-path]');",
  "        if (copyPathBtn) {",
  "          const dir = copyPathBtn.getAttribute('data-copy-path');",
  "          if (navigator.clipboard && navigator.clipboard.writeText) {",
  "            navigator.clipboard.writeText(dir).catch(() => {});",
  "          }",
  "          showToast(`已定位并复制目录路径：${dir}`);",
  "          return;",
  "        }",
  "",
  "        if (e.target.id === 'folder-modal' || e.target.closest('#btn-close-folder')) {",
  "          document.getElementById('folder-modal').classList.add('hidden');",
  "          document.getElementById('folder-modal').classList.remove('flex');",
  "          return;",
  "        }",
  "",
  "        const navBtn = e.target.closest('[data-nav-depth]');",
  "        if (navBtn) {",
  "          popSubgraphToDepth(Number(navBtn.getAttribute('data-nav-depth')));",
  "          return;",
  "        }",
  "",
  "        const ctxSimple = e.target.closest('[data-ctx-simple]');",
  "        if (ctxSimple) {",
  "          const cmd = ctxSimple.getAttribute('data-ctx-simple');",
  "          closeCascadingMenus();",
  "          if (cmd === 'add-ws-blank') {",
  "            const graph = getActiveWorkshopGraph();",
  "            const id = 'n-' + Date.now();",
  "            graph.nodes.push(instantiateWorkshopNode('tpl-blank', id, state.ctxWorldPos.x, state.ctxWorldPos.y));",
  "            state.selectedNodeIds = new Set([id]);",
  "            renderAll();",
  "          } else if (cmd === 'add-sb-blank') {",
  "            const cont = getActiveSandboxContainer();",
  "            const id = 'sb-' + Date.now();",
  "            cont.nodes.push({",
  "              id, step: String(cont.nodes.length + 1).padStart(2, '0'), title: '待定新业务环节',",
  "              tip: '选中后在右侧让子代理补充业务定义', isBlank: true, bypassed: false, collapsed: false, expanded: false,",
  "              x: state.ctxWorldPos.x, y: state.ctxWorldPos.y, w: 252, h: null, nextIds: [], modules: []",
  "            });",
  "            state.selectedNodeIds = new Set([id]);",
  "            renderAll();",
  "          } else if (cmd === 'auto-tidy-selected') {",
  "            autoArrangeNodesSubset(state.selectedNodeIds);",
  "          } else if (cmd === 'auto-tidy') {",
  "            autoArrangeActiveGraph();",
  "          } else if (cmd === 'paste-sb-node') {",
  "            pasteCopiedNode(state.ctxWorldPos);",
  "          } else if (cmd === 'back-host') {",
  "            state.viewingRepoId = state.hostWorkspaceId;",
  "            state.drillFromRepoId = null;",
  "            state.sbSubgraphStack = [];",
  "            renderAll();",
  "            requestAnimationFrame(fitCanvas);",
  "          }",
  "          return;",
  "        }",
  "",
  "        const tbBtn = e.target.closest('[data-tb-act]');",
  "        if (tbBtn) {",
  "          const act = tbBtn.getAttribute('data-tb-act');",
  "          if (act === 'toggle-color-grid') {",
  "            state.colorPickerOpen = !state.colorPickerOpen;",
  "            renderSelectionFloatingToolbox();",
  "          } else if (act === 'group-nodes') createGroupFromSelection();",
  "          else if (act === 'merge-subgraph') mergeSelectedIntoSubgraph();",
  "          else if (act === 'subgraph-to-group') {",
  "            const firstId = [...state.selectedNodeIds][0];",
  "            if (firstId) convertSubgraphToGroup(firstId);",
  "          } else if (act === 'unpack-subgraph') unpackSelectedSubgraph();",
  "          else if (act === 'tidy-group' && state.selectedGroupId) {",
  "            const grp = getActiveGroupsList().find((g) => g.id === state.selectedGroupId);",
  "            if (grp) autoArrangeNodesSubset(new Set(grp.memberIds));",
  "          } else if (act === 'ungroup' && state.selectedGroupId) {",
  "            ungroupById(state.selectedGroupId);",
  "          } else if (act === 'bypass') toggleSelectedBypass();",
  "          else if (act === 'collapse') toggleSelectedCollapse();",
  "          else if (act === 'copy-node') copySelectedNodeToClipboard();",
  "          else if (act === 'delete') deleteSelectedItems();",
  "          return;",
  "        }",
  "",
  "        const pgBtn = e.target.closest('[data-page]');",
  "        if (pgBtn) {",
  "          state.page = pgBtn.getAttribute('data-page');",
  "          state.leftTab = state.page === 'sandbox' ? 'assets' : 'workflows';",
  "          state.selectedGroupId = null;",
  "          state.editingGroupId = null;",
  "          state.colorPickerOpen = false;",
  "          state.selectedLinkId = null;",
  "          const nodes = getActiveNodesList();",
  "          state.selectedNodeIds = nodes[0] ? new Set([nodes[0].id]) : new Set();",
  "          renderAll();",
  "          requestAnimationFrame(fitCanvas);",
  "          return;",
  "        }",
  "",
  "        const sbLay = e.target.closest('[data-sb-layout]');",
  "        if (sbLay) {",
  "          state.sandboxLayout = sbLay.getAttribute('data-sb-layout');",
  "          renderAll();",
  "          requestAnimationFrame(fitCanvas);",
  "          return;",
  "        }",
  "",
  "        const swPack = e.target.closest('[data-switch-pack]');",
  "        if (swPack && !e.target.closest('[data-action]')) {",
  "          state.activePackId = swPack.getAttribute('data-switch-pack');",
  "          state.wsSubgraphStack = [];",
  "          state.selectedGroupId = null;",
  "          state.editingGroupId = null;",
  "          state.colorPickerOpen = false;",
  "          state.selectedLinkId = null;",
  "          const first = WORKFLOW_PACKS[state.activePackId].nodes.find((n) => n.isBlank) || WORKFLOW_PACKS[state.activePackId].nodes[0];",
  "          state.selectedNodeIds = first ? new Set([first.id]) : new Set();",
  "          renderAll();",
  "          requestAnimationFrame(fitCanvas);",
  "          return;",
  "        }",
  "",
  "        const viewRepoEl = e.target.closest('[data-view-repo]');",
  "        if (viewRepoEl && !e.target.closest('[data-action]')) {",
  "          const rid = viewRepoEl.getAttribute('data-view-repo');",
  "          state.viewingRepoId = rid;",
  "          state.drillFromRepoId = null;",
  "          state.sbSubgraphStack = [];",
  "          state.selectedGroupId = null;",
  "          state.editingGroupId = null;"
  ].join('\n');
}
