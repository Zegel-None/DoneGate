// 无限画布视窗矩阵变换、自适应居中、剪贴板复制粘贴、跳过折叠与跨子仓钻取操作
export function buildWbViewportOps() {
  return [
  "    // 14. 视窗、卡片右下角缩放、拖拽与快捷键总控",
  "    // ============================================================================",
  "    function applyViewportTransform() {",
  "      const world = document.getElementById('canvas-world');",
  "      const stage = document.getElementById('canvas-stage');",
  "      const px = Math.round(state.panX);",
  "      const py = Math.round(state.panY);",
  "      world.style.transform = `translate(${px}px, ${py}px) scale(${state.zoom.toFixed(3)})`;",
  "      if (stage) {",
  "        const step = Math.max(9, 22 * state.zoom);",
  "        stage.style.backgroundSize = `${step.toFixed(2)}px ${step.toFixed(2)}px`;",
  "        stage.style.backgroundPosition = `${((px % step) + step) % step}px ${((py % step) + step) % step}px`;",
  "      }",
  "      document.getElementById('btn-zoom-pct').textContent = `${Math.round(state.zoom * 100)}%`;",
  "    }",
  "",
  "    function fitCanvas() {",
  "      const stage = document.getElementById('canvas-stage');",
  "      const cards = stage.querySelectorAll('.node-card, .group-frame');",
  "      if (!cards.length) return;",
  "",
  "      let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;",
  "      cards.forEach((el) => {",
  "        minX = Math.min(minX, el.offsetLeft);",
  "        minY = Math.min(minY, el.offsetTop);",
  "        maxX = Math.max(maxX, el.offsetLeft + el.offsetWidth);",
  "        maxY = Math.max(maxY, el.offsetTop + el.offsetHeight + 36);",
  "      });",
  "",
  "      const padX = 42;",
  "      const padY = 48;",
  "      const w = Math.max(300, maxX - minX);",
  "      const h = Math.max(220, maxY - minY);",
  "      const availW = Math.max(260, stage.clientWidth - padX * 2);",
  "      const availH = Math.max(180, stage.clientHeight - padY * 2 - 116);",
  "",
  "      const scale = Math.min(1.0, Math.max(0.20, Math.min(availW / w, availH / h)));",
  "      state.zoom = scale;",
  "      state.panX = Math.round(padX + Math.max(0, (availW - w * scale) / 2) - minX * scale);",
  "      state.panY = Math.round(padY + Math.max(0, (availH - h * scale) / 2) - minY * scale);",
  "      applyViewportTransform();",
  "      requestAnimationFrame(() => {",
  "        renderWires(null);",
  "        renderSelectionFloatingToolbox();",
  "      });",
  "    }",
  "",
  "    let toastTimer = null;",
  "    function showToast(msg) {",
  "      const el = document.getElementById('toast-pill');",
  "      el.textContent = msg;",
  "      el.style.opacity = '1';",
  "      if (toastTimer) clearTimeout(toastTimer);",
  "      toastTimer = setTimeout(() => { el.style.opacity = '0'; }, 2400);",
  "    }",
  "",
  "    function renderAll() {",
  "      renderHeader();",
  "      renderLeftDrawer();",
  "      renderCanvas();",
  "      renderRightSidebar();",
  "      applyViewportTransform();",
  "      applyAllControlStyleOverrides();",
  "      applyAllTextOverridesAndSelection();",
  "    }",
  "",
  "    function copySelectedNodeToClipboard() {",
  "      const nodes = getActiveNodesList();",
  "      const first = nodes.find((n) => state.selectedNodeIds.has(n.id) && !n.isBoundary);",
  "      if (!first) return;",
  "      state.copiedNodeData = JSON.parse(JSON.stringify(first));",
  "      renderAll();",
  "      showToast(isSandboxReadOnly()",
  "        ? `已复制外部仓节点「${first.title}」，切回置顶本仓即可粘贴`",
  "        : `已复制「${first.title}」 (Ctrl+V 可粘贴)`);",
  "    }",
  "",
  "    function pasteCopiedNode(atPos) {",
  "      if (!state.copiedNodeData || isSandboxReadOnly()) return;",
  "      const copy = JSON.parse(JSON.stringify(state.copiedNodeData));",
  "      copy.id = 'paste-' + Date.now();",
  "      copy.isSubRepoRef = false;",
  "      copy.x = atPos ? atPos.x : (copy.x + 36);",
  "      copy.y = atPos ? atPos.y : (copy.y + 36);",
  "",
  "      if (state.page === 'workshop') {",
  "        getActiveWorkshopGraph().nodes.push(copy);",
  "      } else {",
  "        copy.nextIds = [];",
  "        getActiveSandboxContainer().nodes.push(copy);",
  "      }",
  "      state.selectedNodeIds = new Set([copy.id]);",
  "      renderAll();",
  "      showToast(`已粘贴节点「${copy.title}」`);",
  "    }",
  "",
  "    function toggleSelectedBypass() {",
  "      if (isSandboxReadOnly()) return;",
  "      const picked = getActiveNodesList().filter((n) => state.selectedNodeIds.has(n.id) && !n.isBoundary);",
  "      if (!picked.length) return;",
  "      const nextVal = picked.some((n) => !n.bypassed);",
  "      picked.forEach((n) => { n.bypassed = nextVal; });",
  "      renderAll();",
  "      showToast(nextVal ? '已设为跳过（上游数据直通下游）' : '已取消跳过');",
  "    }",
  "",
  "    function toggleSelectedCollapse() {",
  "      const picked = getActiveNodesList().filter((n) => state.selectedNodeIds.has(n.id) && !n.isBoundary);",
  "      if (!picked.length) return;",
  "      const nextVal = picked.some((n) => !n.collapsed);",
  "      picked.forEach((n) => { n.collapsed = nextVal; });",
  "      renderAll();",
  "    }",
  "",
  "    function deleteSelectedItems() {",
  "      if (isSandboxReadOnly()) {",
  "        showToast('外部参考看板为只读模式');",
  "        return;",
  "      }",
  "      if (state.selectedGroupId && state.selectedNodeIds.size === 0) {",
  "        ungroupById(state.selectedGroupId);",
  "        return;",
  "      }",
  "      if (state.selectedLinkId) {",
  "        if (state.page === 'workshop') {",
  "          const graph = getActiveWorkshopGraph();",
  "          graph.links = graph.links.filter((l) => l.id !== state.selectedLinkId);",
  "        } else if (state.selectedLinkId.startsWith('sb:')) {",
  "          const [f, t] = state.selectedLinkId.slice(3).split('->');",
  "          const src = getActiveSandboxContainer().nodes.find((n) => n.id === f);",
  "          if (src) src.nextIds = (src.nextIds || []).filter((id) => id !== t);",
  "        }",
  "        state.selectedLinkId = null;",
  "        renderAll();",
  "        showToast('已断开连线');",
  "        return;",
  "      }",
  "      const deletableIds = new Set(",
  "        getActiveNodesList().filter((n) => state.selectedNodeIds.has(n.id) && !n.isBoundary).map((n) => n.id)",
  "      );",
  "      if (deletableIds.size > 0) {",
  "        if (state.page === 'workshop') {",
  "          const graph = getActiveWorkshopGraph();",
  "          graph.nodes = graph.nodes.filter((n) => !deletableIds.has(n.id));",
  "          graph.links = graph.links.filter((l) => !deletableIds.has(l.fromNode) && !deletableIds.has(l.toNode));",
  "        } else {",
  "          const cont = getActiveSandboxContainer();",
  "          cont.nodes = cont.nodes.filter((n) => !deletableIds.has(n.id));",
  "          cont.nodes.forEach((n) => { n.nextIds = (n.nextIds || []).filter((id) => !deletableIds.has(id)); });",
  "        }",
  "        state.selectedNodeIds.clear();",
  "        renderAll();",
  "        showToast('已删除选中卡片');",
  "      }",
  "    }",
  "",
  "    function drillIntoSubRepo(subRepoId) {",
  "      if (!REPO_SANDBOXES[subRepoId]) return;",
  "      state.sbSubgraphStack = [];",
  "      state.drillFromRepoId = state.viewingRepoId;",
  "      state.viewingRepoId = subRepoId;",
  "      state.selectedNodeIds.clear();",
  "      state.selectedLinkId = null;",
  "      renderAll();",
  "      requestAnimationFrame(fitCanvas);",
  "      showToast(`已下钻进入「${REPO_SANDBOXES[subRepoId].name}」只读预览`);",
  "    }",
  "",
  "    function importExternalRepoAsSummaryNode(repoId, pos) {",
  "      const ext = REPO_SANDBOXES[repoId];",
  "      const host = REPO_SANDBOXES[state.hostWorkspaceId];",
  "      if (!ext || !host) return;",
  "      state.viewingRepoId = state.hostWorkspaceId;",
  "      state.drillFromRepoId = null;",
  "      state.sbSubgraphStack = [];",
  "",
  "      const existing = host.nodes.find((n) => n.isSubRepoRef && n.refRepoId === repoId);",
  "      if (existing) {",
  "        state.selectedNodeIds = new Set([existing.id]);",
  "        renderAll();",
  "        showToast(`「${ext.name}」已在当前看板中`);",
  "        return;",
  "      }",
  "",
  "      const newId = 'subref-' + Date.now();",
  "      host.nodes.push({",
  "        id: newId,",
  "        step: '子仓',",
  "        title: ext.name,",
  "        isSubRepoRef: true,",
  "        refRepoId: repoId,",
  "        tip: `引用自外部仓库 ${ext.repoSlug} 的汇总总节点 · 双击卡片可下钻查看内部看板`,",
  "        bypassed: false, collapsed: false, expanded: false,",
  "        x: pos ? pos.x : 360, y: pos ? pos.y : 260, w: 252, h: null,",
  "        nextIds: [], modules: []",
  "      });",
  "      state.selectedNodeIds = new Set([newId]);",
  "      renderAll();",
  "      showToast(`已将「${ext.name}」作为总节点引入当前看板`);",
  "    }",
  ""
  ].join('\n');
}
