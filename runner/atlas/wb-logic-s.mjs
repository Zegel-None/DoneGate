// 工作台交互逻辑分片 S（零外网依赖单文件工作台分片模块，严格 <= 300 行）
export function buildWbLogicS() {
  return [
  "        if (resizeSide === 'left') {",
  "          const drawerW = e.clientX - 52;",
  "          if (drawerW < 95) { state.leftOpen = false; resizeSide = null; leftSplitter.classList.remove('is-dragging'); renderLeftDrawer(); return; }",
  "          state.leftWidth = Math.min(400, Math.max(172, drawerW));",
  "          document.getElementById('left-drawer').style.width = `${state.leftWidth}px`;",
  "          return;",
  "        }",
  "        if (resizeSide === 'right') {",
  "          const w = window.innerWidth - e.clientX;",
  "          if (w < 120) { state.rightOpen = false; resizeSide = null; rightSplitter.classList.remove('is-dragging'); renderRightSidebar(); return; }",
  "          state.rightWidth = Math.min(540, Math.max(256, w));",
  "          document.getElementById('right-sidebar').style.width = `${state.rightWidth}px`;",
  "          return;",
  "        }",
  "",
  "        // Card Bottom-Right Corner Free Resize with ComfyUI computeSize() Clipping + Visual Studio Snaplines!",
  "        if (cardResize) {",
  "          const dx = (e.clientX - cardResize.startX) / state.zoom;",
  "          const dy = (e.clientY - cardResize.startY) / state.zoom;",
  "          const obj = getActiveNodesList().find((n) => n.id === cardResize.nodeId);",
  "          const dom = document.getElementById(`card-${cardResize.nodeId}`);",
  "          if (obj && dom) {",
  "            const floor = getCardMinFloor(obj, dom);",
  "            const rawW = Math.min(580, Math.max(floor.minW, Math.round(cardResize.origW + dx)));",
  "            const rawH = Math.min(640, Math.max(floor.minH, Math.round(cardResize.origH + dy)));",
  "            const snapped = computeResizeWithVsSnap(cardResize.nodeId, rawW, rawH, floor.minW, floor.minH);",
  "            obj.w = snapped.w;",
  "            obj.h = snapped.h;",
  "            dom.style.width = `${obj.w}px`;",
  "            syncCardResponsiveState(dom, obj);",
  "            syncGroupFramesGeometry();",
  "            renderWires(null);",
  "            renderSelectionFloatingToolbox();",
  "          }",
  "          return;",
  "        }",
  "",
  "        if (menuHold) {",
  "          const dist = Math.hypot(e.clientX - menuHold.startX, e.clientY - menuHold.startY);",
  "          if (!menuHold.dragging && dist > 6) {",
  "            clearTimeout(menuHold.timer);",
  "            menuHold.dragging = true;",
  "          }",
  "          if (menuHold.dragging) {",
  "            dragGhost.style.display = 'block';",
  "            dragGhost.textContent = `拖动改分类：${menuHold.title}`;",
  "            dragGhost.style.left = `${e.clientX + 12}px`;",
  "            dragGhost.style.top = `${e.clientY + 12}px`;",
  "            rootMenu.querySelectorAll('.is-drop-target').forEach((el) => el.classList.remove('is-drop-target'));",
  "            const dropFolder = e.target.closest('[data-cat-folder], [data-new-cat-drop]');",
  "            if (dropFolder) dropFolder.classList.add('is-drop-target');",
  "            return;",
  "          }",
  "        }",
  "",
  "        const folderRow = e.target.closest('[data-cat-folder]');",
  "        if (folderRow && !menuHold && !rootMenu.classList.contains('hidden')) {",
  "          const cat = folderRow.getAttribute('data-cat-folder');",
  "          if (state.ctxOpenCat !== cat) openSubMenuForCategory(cat, folderRow);",
  "        }",
  "",
  "        const tipEl = e.target.closest('[data-tip]');",
  "        if (tipEl && !panDrag && !cardDrag && !cardResize && !wireDrag && !boxSelect && !menuHold) {",
  "          const txt = tipEl.getAttribute('data-tip');",
  "          if (txt) {",
  "            tooltip.textContent = txt;",
  "            tooltip.classList.add('is-visible');",
  "            tooltip.style.left = `${Math.max(8, Math.min(window.innerWidth - 280, e.clientX + 14))}px`;",
  "            tooltip.style.top = `${Math.max(8, Math.min(window.innerHeight - 90, e.clientY + 14))}px`;",
  "            return;",
  "          }",
  "        }",
  "        tooltip.classList.remove('is-visible');",
  "      });",
  "",
  "      subMenu.addEventListener('pointerdown', (e) => {",
  "        const subRepoItem = e.target.closest('[data-summon-subrepo]');",
  "        if (subRepoItem) {",
  "          const rid = subRepoItem.getAttribute('data-summon-subrepo');",
  "          closeCascadingMenus();",
  "          importExternalRepoAsSummaryNode(rid, state.ctxWorldPos);",
  "          return;",
  "        }",
  "        const tplItem = e.target.closest('[data-menu-tpl]');",
  "        if (!tplItem || e.button !== 0) return;",
  "        e.preventDefault();",
  "        const tplId = tplItem.getAttribute('data-menu-tpl');",
  "        const tpl = BLOCK_TEMPLATES[tplId];",
  "        if (!tpl) return;",
  "",
  "        const timer = setTimeout(() => {",
  "          if (menuHold) {",
  "            menuHold.dragging = true;",
  "            dragGhost.style.display = 'block';",
  "            dragGhost.textContent = `拖动改分类：${tpl.title}`;",
  "            dragGhost.style.left = `${e.clientX + 12}px`;",
  "            dragGhost.style.top = `${e.clientY + 12}px`;",
  "          }",
  "        }, 210);",
  "        menuHold = { tplId, title: tpl.title, startX: e.clientX, startY: e.clientY, timer, dragging: false };",
  "      });",
  "",
  "      window.addEventListener('pointerup', (e) => {",
  "        if (resizeSide) {",
  "          resizeSide = null;",
  "          leftSplitter.classList.remove('is-dragging');",
  "          rightSplitter.classList.remove('is-dragging');",
  "        }",
  "        if (cardResize) {",
  "          cardResize = null;",
  "          clearSnaplines();",
  "          return;",
  "        }",
  "        if (menuHold) {",
  "          clearTimeout(menuHold.timer);",
  "          dragGhost.style.display = 'none';",
  "          rootMenu.querySelectorAll('.is-drop-target').forEach((el) => el.classList.remove('is-drop-target'));",
  "",
  "          if (!menuHold.dragging) {",
  "            const graph = getActiveWorkshopGraph();",
  "            const newId = 'n-' + Date.now();",
  "            const created = instantiateWorkshopNode(menuHold.tplId, newId, state.ctxWorldPos.x, state.ctxWorldPos.y);",
  "            graph.nodes.push(created);",
  "            state.selectedNodeIds = new Set([newId]);",
  "            state.selectedLinkId = null;",
  "            closeCascadingMenus();",
  "            renderAll();",
  "            showToast(`已召唤「${created.title}」`);",
  "          } else {",
  "            const dropFolder = e.target.closest('[data-cat-folder]');",
  "            const dropNewCat = e.target.closest('[data-new-cat-drop]');",
  "            const tpl = BLOCK_TEMPLATES[menuHold.tplId];",
  "            if (tpl && dropFolder) {",
  "              const nextCat = dropFolder.getAttribute('data-cat-folder');",
  "              if (nextCat && nextCat !== '__subrepos__') {",
  "                tpl.category = nextCat;",
  "                openSubMenuForCategory(nextCat, dropFolder);",
  "                showToast(`已将「${tpl.title}」移入分类「${nextCat}」`);",
  "              }",
  "            } else if (tpl && dropNewCat) {",
  "              const customCat = `自定义组 ${CATEGORY_LIST.length - 4}`;",
  "              CATEGORY_LIST.push(customCat);",
  "              tpl.category = customCat;",
  "              const rRect = rootMenu.getBoundingClientRect();",
  "              openCanvasCascadingMenu(rRect.left, rRect.top);",
  "              const newRow = rootMenu.querySelector(`[data-cat-folder=\"${customCat}\"]`);",
  "              if (newRow) openSubMenuForCategory(customCat, newRow);",
  "              showToast(`已新建分类「${customCat}」`);",
  "            }",
  "          }",
  "          menuHold = null;",
  "          return;",
  "        }",
  "",
  "        if (panDrag) { panDrag = null; stage.style.cursor = 'default'; return; }",
  "        if (groupDrag) { groupDrag = null; clearSnaplines(); renderSelectionFloatingToolbox(); return; }",
  "        if (cardDrag) { cardDrag = null; clearSnaplines(); syncGroupFramesGeometry(); renderSelectionFloatingToolbox(); return; }",
  "",
  "        if (wireDrag) {",
  "          document.querySelectorAll('.is-snap-target').forEach((p) => p.classList.remove('is-snap-target'));",
  "          const targetPin = e.target.closest('[data-port-dir]');",
  "          if (targetPin && !isSandboxReadOnly()) {",
  "            const tDir = targetPin.getAttribute('data-port-dir');",
  "            const tNode = targetPin.getAttribute('data-port-node');",
  "            const tSlot = targetPin.getAttribute('data-port-slot');",
  "            const tType = targetPin.getAttribute('data-port-type') || 'ANY';",
  "",
  "            if (tDir !== wireDrag.originDir) {",
  "              const fromNode = wireDrag.originDir === 'out' ? wireDrag.originNode : tNode;",
  "              const fromSlot = wireDrag.originDir === 'out' ? wireDrag.originSlot : tSlot;",
  "              const fromType = wireDrag.originDir === 'out' ? wireDrag.type : tType;",
  "              const toNode = wireDrag.originDir === 'in' ? wireDrag.originNode : tNode;",
  "              const toSlot = wireDrag.originDir === 'in' ? wireDrag.originSlot : tSlot;",
  "",
  "              if (state.page === 'workshop') {",
  "                const graph = getActiveWorkshopGraph();",
  "                if (!graph.links.some((l) => l.fromNode === fromNode && l.fromSlot === fromSlot && l.toNode === toNode && l.toSlot === toSlot)) {",
  "                  const id = 'lk-' + Date.now();",
  "                  const isSelf = fromNode === toNode;",
  "                  graph.links.push({",
  "                    id, fromNode, fromSlot, toNode, toSlot,",
  "                    type: fromType === 'ANY' ? tType : fromType,",
  "                    ...(isSelf ? { maxLoops: 3 } : {})",
  "                  });",
  "                  state.selectedLinkId = id;",
  "                  state.selectedNodeIds.clear();",
  "                  showToast(isSelf ? '已建立同卡自循环（默认上限 3 次）' : '连线已建立');",
  "                }",
  "              } else {",
  "                const src = getActiveSandboxContainer().nodes.find((n) => n.id === fromNode);",
  "                if (src && !src.nextIds.includes(toNode)) src.nextIds.push(toNode);",
  "              }",
  "            }",
  "          }",
  "          wireDrag = null;",
  "          renderAll();",
  "          return;",
  "        }",
  "",
  "        if (boxSelect) {",
  "          const x1 = Math.min(boxSelect.startX, e.clientX);",
  "          const y1 = Math.min(boxSelect.startY, e.clientY);",
  "          const x2 = Math.max(boxSelect.startX, e.clientX);",
  "          const y2 = Math.max(boxSelect.startY, e.clientY);",
  "          const keepPrev = Boolean(e.shiftKey);",
  "          marquee.style.display = 'none';",
  "          boxSelect = null;",
  "",
  "          if (x2 - x1 > 6 && y2 - y1 > 6) {",
  "            const picked = new Set(keepPrev ? state.selectedNodeIds : []);",
  "            stage.querySelectorAll('[data-card-id]').forEach((el) => {",
  "              const r = el.getBoundingClientRect();",
  "              if (!(r.right < x1 || r.left > x2 || r.bottom < y1 || r.top > y2)) {",
  "                picked.add(el.getAttribute('data-card-id'));",
  "              }",
  "            });",
  "            state.selectedNodeIds = picked;",
  "            state.selectedLinkId = null;",
  "            renderAll();",
  "            state.selectedGroupId = null;",
  "            state.activeFocusTarget = 'canvas';",
  "            if (picked.size > 1) showToast(`已框选 ${picked.size} 张卡片，点上方「组合」加背景框，或点「合并」折叠为子节点`);",
  "          }",
  "        }",
  "      });",
  "",
  "      stage.addEventListener('contextmenu', (e) => {",
  "        e.preventDefault();",
  "        const wr = document.getElementById('canvas-world').getBoundingClientRect();",
  "        state.ctxWorldPos = {",
  "          x: Math.round((e.clientX - wr.left) / state.zoom - 110),",
  "          y: Math.round((e.clientY - wr.top) / state.zoom - 20)",
  "        };",
  "",
  "        const hitCard = e.target.closest('[data-card-id]');",
  "        if (hitCard) {",
  "          const cid = hitCard.getAttribute('data-card-id');",
  "          if (!state.selectedNodeIds.has(cid)) {",
  "            state.selectedNodeIds = new Set([cid]);",
  "            state.selectedLinkId = null;",
  "            renderAll();",
  "          }",
  "          openCardContextMenu(e.clientX, e.clientY, cid);",
  "          return;",
  "        }"
  ].join('\n');
}
