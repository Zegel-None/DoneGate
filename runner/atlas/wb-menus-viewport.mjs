  "          const clean = String(sp || '').trim();",
  "          if (!clean) return;",
  "          const dir = clean.endsWith('/') ? clean : (clean.includes('/') ? clean.slice(0, clean.lastIndexOf('/') + 1) : `${clean}/`);",
